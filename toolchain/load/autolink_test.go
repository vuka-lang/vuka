// TestAutoLink: which packages count as declarer packages — a declarer
// function, a declarer call, a type decorator, a composed decorator from
// another package — and which don't: call decorators and typed attributes
// alone, declarations in test files, //vuka:nolink. Every main of the module
// gets the link file, an example's packages only that example's main, and a
// //vuka:nolink main none.
func TestAutoLink(t *testing.T) {
	if testing.Short() {
		t.Skip("runs the go command")
	}
	t.Setenv("GOFLAGS", "-mod=mod")
	t.Setenv("GOWORK", "off")
	repo, _ := filepath.Abs("../..")
	root := filepath.Join(t.TempDir(), "app")
	write(t, filepath.Join(root, "go.mod"), "module example.com/app\n\ngo 1.23\n\nrequire github.com/vuka-lang/vuka/v2 v2.0.0\n\nreplace github.com/vuka-lang/vuka/v2 => "+repo+"\n")
	write(t, filepath.Join(root, "reg", "reg.vuka"), `package reg

import "github.com/vuka-lang/vuka/v2"

var Routes []string

func Route(path string) func(*vuka.Decl) {
	return func(d *vuka.Decl) { Routes = append(Routes, path) }
}

func Register(d *vuka.Decl) { Routes = append(Routes, d.Name) }

func Model(t *vuka.Type) {}

decorator timed(c) {
	c.Next()
}

decorator Page(path string) = @Route(path) @timed
`)
	write(t, filepath.Join(root, "pages", "bycall", "a.vuka"), "package bycall\n\nimport \"example.com/app/reg\"\n\n@reg.Route(\"/a\")\nfunc A() {}\n")
	write(t, filepath.Join(root, "pages", "byfunc", "b.vuka"), "package byfunc\n\nimport \"example.com/app/reg\"\n\n@reg.Register\nfunc B() {}\n")
	write(t, filepath.Join(root, "pages", "bytype", "m.vuka"), "package bytype\n\nimport \"example.com/app/reg\"\n\n@reg.Model\ntype M struct{}\n")
	write(t, filepath.Join(root, "pages", "bybundle", "c.vuka"), "package bybundle\n\nimport \"example.com/app/reg\"\n\n@reg.Page(\"/c\")\nfunc C() {}\n")
	write(t, filepath.Join(root, "pages", "callonly", "d.vuka"), "package callonly\n\ndecorator logged(c) {\n\tc.Next()\n}\n\n@logged\nfunc D() {}\n")
	write(t, filepath.Join(root, "pages", "attronly", "e.vuka"), "package attronly\n\ntype Tag string\n\n@Tag(\"x\")\nfunc E() {}\n")
	write(t, filepath.Join(root, "pages", "optout", "f.vuka"), "//vuka:nolink\npackage optout\n\nimport \"example.com/app/reg\"\n\n@reg.Route(\"/skip\")\nfunc F() {}\n")
	write(t, filepath.Join(root, "pages", "testonly", "g.vuka"), "package testonly\n\nfunc G() {}\n")
	write(t, filepath.Join(root, "pages", "testonly", "g_test.vuka"), "package testonly\n\nimport \"example.com/app/reg\"\n\n@reg.Route(\"/test-only\")\nfunc H() {}\n")
	write(t, filepath.Join(root, "examples", "demo", "widgets", "w.vuka"), "package widgets\n\nimport \"example.com/app/reg\"\n\n@reg.Route(\"/w\")\nfunc W() {}\n")
	write(t, filepath.Join(root, "examples", "demo", "main.vuka"), "package main\n\nfunc main() {}\n")
	write(t, filepath.Join(root, "tools", "curated", "main.vuka"), "//vuka:nolink\npackage main\n\nfunc main() {}\n")
	write(t, filepath.Join(root, "main.vuka"), "package main\n\nimport (\n\t\"fmt\"\n\n\t\"example.com/app/reg\"\n)\n\nfunc main() { fmt.Println(reg.Routes) }\n")

	if r, err := filepath.EvalSymlinks(root); err == nil {
		root = r
	}
	pkgs, err := Discover(root, "example.com/app", root, true, nil)
	if err != nil {
		t.Fatal(err)
	}
	gens, _, err := Transpile(pkgs, t.TempDir(), Options{})
	if err != nil {
		t.Fatal(err)
	}
	links, linked, err := AutoLink(root, "example.com/app", pkgs, gens)
	if err != nil {
		t.Fatal(err)
	}
	byDir := map[string][]string{}
	for _, m := range linked {
		rel, _ := filepath.Rel(root, m.Dir)
		byDir[filepath.ToSlash(rel)] = m.Imports
	}
	want := []string{
		"example.com/app/pages/bybundle",
		"example.com/app/pages/bycall",
		"example.com/app/pages/byfunc",
		"example.com/app/pages/bytype",
	}
	if got := byDir["."]; !slices.Equal(got, want) {
		t.Errorf("the root main links %q, want %q", got, want)
	}
	if got, want := byDir["examples/demo"], append([]string{"example.com/app/examples/demo/widgets"}, want...); !slices.Equal(got, want) {
		t.Errorf("the example's main links %q, want %q", got, want)
	}
	if _, ok := byDir["tools/curated"]; ok {
		t.Error("the //vuka:nolink main got a link file")
	}
	if len(links) != 2 {
		t.Errorf("%d link files, want 2", len(links))
	}
	for _, g := range links {
		if filepath.Base(g.Target) != LinkGoName {
			t.Errorf("link file named %s", g.Target)
		}
		if !strings.HasPrefix(string(g.Src), "// Code generated by vuka. DO NOT EDIT.\n") || !strings.Contains(string(g.Src), "\npackage main\n") {
			t.Errorf("link file content:\n%s", g.Src)
		}
	}

	// With the declarer packages gone, a main keeps a link file only when one
	// is already on disk — then an empty one, so the stale imports never
	// break the build.
	links, _, err = AutoLink(root, "example.com/app", pkgs, nil)
	if err != nil {
		t.Fatal(err)
	}
	if len(links) != 0 {
		t.Errorf("no declarers, no disk file: got %d link files", len(links))
	}
	if err := os.WriteFile(filepath.Join(root, LinkGoName), []byte("stale"), 0o644); err != nil {
		t.Fatal(err)
	}
	links, _, err = AutoLink(root, "example.com/app", pkgs, nil)
	if err != nil {
		t.Fatal(err)
	}
	if len(links) != 1 || strings.Contains(string(links[0].Src), "\t_ \"") {
		t.Errorf("a stale disk file should come back empty: %v", links)
	}
}

func TestAutoLinkVisible(t *testing.T) {
	for _, c := range []struct {
		importer, imported string
		want               bool
	}{
		{"cmd/app", "pages/admin", true},
		{"cmd/app", "internal/pages", true},
		{"examples/live", "auth/internal/gatetest", false},
		{"auth/cmd", "auth/internal/gatetest", true},
		{"auth", "auth/internal/gatetest", true},
		{"authx", "auth/internal/gatetest", false},
		{"a/internal/b", "a/internal/b/internal/c", true},
		{"a/internal/x", "a/internal/b/internal/c", false},
	} {
		if got := visible(c.importer, c.imported); got != c.want {
			t.Errorf("visible(%q, %q) = %v, want %v", c.importer, c.imported, got, c.want)
		}
	}
}
