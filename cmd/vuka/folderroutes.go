// Folder routes: the module's pages/ directory is a tree of packages whose
// folder path is the URL, and so is a pages/ directory beside a package
// main elsewhere in the module, the routes of that main's app. A bracketed name is a path parameter: a [id]
// folder (seen by the go command by its Go name, param_id: load.GoDir) or a [id]
// file in a folder; [path...] takes the rest of the path. A folder in
// parentheses, (admin), is a route group: it adds no segment to the URL (the
// go command sees it as group_admin), and its layout, Guard and Middleware
// are those of the pages inside it alone. A folder's
// _layout.vuka.html wraps the pages below it, and its Guard and Middleware
// check and wrap them. pages/route.go, package pages, holds func Routes, a
// web.Option registering every page, its method handlers, every endpoint
// and method func, and the guards, layouts and middleware over them on the
// app; pages/urls/urls_gen.go, the package urls, is their paths as a chain
// of values (urls.Orgs.Org(7).Edit.Path()) importing no page package, so
// any page links to any other.
//
// The page packages use urls while they are transpiled, before their types
// are known: urls is transpiled as a stub read from the sources (every page
// a field, parameters taken as ...any), and route.go as a stub registering
// nothing; both go in the overlay after their package (load.AfterPackage),
// over any written to disk earlier. Once the module is transpiled, the page
// packages are type-checked from the overlay, the route table is built from
// their types, and the real files replace the stubs in the overlay.

const (
	pagesDirName  = "pages"
	routeGoName   = "route.go"      // pages/route.go: every route, func Routes() web.Option
	routesGoName  = "routes_gen.go" // 1.x's, in each page folder: E0718
	pagesGoName   = "pages_gen.go"  // 1.x's pages/pages_gen.go: E0718
	urlsGoName    = "urls_gen.go"
	urlsDirName   = "urls"
	routesStub    = "vuka_routes_stub.vuka"
	routesHeading = "// Code generated by vuka from the folders under pages/. DO NOT EDIT.\n\n"
)

// routeTree is the page packages under one pages/ directory: the
// module's, or the one beside a package main (main, its directory).
type routeTree struct {
	root, modPath string
	pages         string            // the pages/ directory
	pagesPath     string            // its import path
	main          string            // the directory of the package main beside it; "" for the module's
	dirs          []*routeDir       // by rel, parents first
	clashes       []diag.Diagnostic // found in the private folders
	declared      []declaredRoute   // the routes the module declares itself
	// registered are the types registered as pages another way, by a
	// decorator on the type (by import path and name) or a call naming
	// their constructor (by name): not folder pages.
	registered map[string]bool
	info       map[*routeDir]*dirInfo
	urls       *urlNode
	result     *routesResult // the last finish's
}

// routeTrees are the module's page trees: its pages/ directory's, and
// those beside its package mains.
type routeTrees []*routeTree

// apply is finish, failing on the route table's errors.
func (ts routeTrees) apply(gens []load.Generated, overlay, tmp string) ([]load.Generated, string, error) {
	gens, overlay, res, err := ts.finish(gens, overlay, tmp)
	if err != nil {
		return nil, "", err
	}
	return gens, overlay, res.err()
}

// files are the files the last finish generated.
func (ts routeTrees) files() []load.Generated {
	var out []load.Generated
	for _, t := range ts {
		if t.result != nil {
			out = append(out, t.result.files...)
		}
	}
	return out
}

// writeFiles writes the files the last finish generated that hand-written
// code imports — each tree's route.go and urls/urls_gen.go — to disk where
// they differ, so an editor and plain Go tools see the packages vuka run
// serves; the overlay holds the same text. It returns the files written.
func (ts routeTrees) writeFiles() ([]string, error) {
	var wrote []string
	for _, g := range ts.files() {
		if old, err := os.ReadFile(g.Target); err == nil && bytes.Equal(old, g.Src) {
			continue
		}
		if err := os.MkdirAll(filepath.Dir(g.Target), 0o755); err != nil {
			return wrote, err
		}
		if err := os.WriteFile(g.Target, g.Src, 0o644); err != nil {
			return wrote, err
		}
		wrote = append(wrote, g.Target)
	}
	return wrote, nil
}

// routeFile reports whether path is one of the files writeFiles writes: a
// pages/route.go or a pages/urls/urls_gen.go.
func routeFile(path string) bool {
	dir := filepath.Dir(path)
	switch filepath.Base(path) {
	case routeGoName:
		return filepath.Base(dir) == pagesDirName
	case urlsGoName:
		return filepath.Base(dir) == urlsDirName && filepath.Base(filepath.Dir(dir)) == pagesDirName
	}
	return false
}

// stub readies pkgs for the transpile, for every tree.
func (ts routeTrees) stub(pkgs []*load.Package) ([]*load.Package, error) {
	clear(routeStubs)
	for _, t := range ts {
		var err error
		if pkgs, err = t.stub(pkgs); err != nil {
			return pkgs, err
		}
	}
	return pkgs, nil
}

// routeDir is one directory under pages/ holding Go or Vuka source.
type routeDir struct {
	dir, rel   string // rel: slash path from pages/ ("" for pages/ itself); [id] for a parameter folder
	goDir      string // where the go command sees the package: dir, or its Go name below a [id] folder (load.GoDir)
	importPath string
	name       string   // the package's name
	pages      []string // the types its sources give a New<T>: its pages, roughly
	goFiles    []string // its .go files, when it has no Vuka source
	layout     string   // the type its _layout.vuka.html renders, "" when it has none
	layoutFile string
	oldLayout  string            // a 1.x layout.vuka.html, for E0715's help
	bracket    map[string]string // a type declared in a [id] file → its parameter, "[id]"
	fileOf     map[string]string // a type declared in a .vuka.html file → the file
	files      map[string]string // a parameter → a file named for it
	funcs      []methodFunc      // its method funcs: GET, POST… declared by a file
	clashes    []diag.Diagnostic // found before the transpile, which they would derail
	vuka       bool              // it has .vuka, .vuka.html or .templ files
}

// methodFunc is an endpoint written as a function named for its HTTP
// method, GET, POST, PUT, PATCH or DELETE: the file declaring it is the
// route (index.vuka its folder, [id].vuka a parameter, list.vuka /list).
type methodFunc struct {
	method string // GET
	goName string // the function's name in the package: GET, or GET_id when files of the package declare it alike
	file   string // [id].vuka
}

// fileSeg is the URL segment of a route file: "" for index, its parameter
// ("[id]") or its name.
func fileSeg(file string) string {
	base := strings.TrimSuffix(strings.TrimSuffix(strings.TrimSuffix(file, ".vuka.html"), ".vuka"), ".go")
	if base == "index" {
		return ""
	}
	return base
}

var (
	ctorDecl   = regexp.MustCompile(`(?m)^func\s+New([A-Z]\w*)\s*[\[(]`)
	typeDecl   = regexp.MustCompile(`(?m)^type\s+([A-Z]\w*)\s`)
	structDecl = regexp.MustCompile(`(?m)^type\s+([A-Z]\w*)\s+struct\b`)
	topFunc    = regexp.MustCompile(`(?m)^(?:func|var|const)\s+([A-Z]\w*)\b`)
	// renderMethod is a Render or View method written in Go, of a type.
	renderMethod = regexp.MustCompile(`(?m)^func\s*\(\s*\w*\s*\*?\s*([A-Z]\w*)\s*\)\s*(?:Render|View)\s*\(`)
	routeAttr    = regexp.MustCompile(`^\w+\.(Get|Post|Put|Patch|Delete|Handle|Live)$`)
	methodDecl   = regexp.MustCompile(`(?m)^func(\s+)(GET|POST|PUT|PATCH|DELETE)(\s*\()`)
)

// scanRoutes finds the page packages of the module at root: those of its
// pages/ directory, and of each pages/ directory beside a package main
// below it; none when it has neither. read reads a source (the editor's
// buffer, for the language server); nil reads the disk.
func scanRoutes(root, modPath string, read load.ReadFunc) routeTrees {
	if read == nil {
		read = os.ReadFile
	}
	root = realPathOf(root)
	var ts routeTrees
	if t := scanRouteTree(root, modPath, "", read); t != nil {
		ts = append(ts, t)
	}
	for _, dir := range mainDirs(root, read) {
		if t := scanRouteTree(root, modPath, dir, read); t != nil {
			ts = append(ts, t)
		}
	}
	return ts
}

// mainDirs are the directories below root holding a package main beside a
// pages/ directory, root itself not included.
func mainDirs(root string, read load.ReadFunc) []string {
	var out []string
	filepath.WalkDir(root, func(path string, e fs.DirEntry, err error) error {
		if err != nil || !e.IsDir() || path == root {
			return nil
		}
		if n := e.Name(); strings.HasPrefix(n, ".") || strings.HasPrefix(n, "_") || n == "testdata" || n == "vendor" || n == "node_modules" ||
			n == pagesDirName || fileExists(filepath.Join(path, "go.mod")) || fileExists(filepath.Join(path, load.Marker)) || load.IsGoName(path) {
			return filepath.SkipDir
		}
		if fi, err := os.Stat(filepath.Join(path, pagesDirName)); err != nil || !fi.IsDir() {
			return nil
		}
		entries, _ := os.ReadDir(path)
		for _, f := range entries {
			n := f.Name()
			if f.IsDir() || strings.Contains(n, "_test.") || !(strings.HasSuffix(n, ".go") || strings.HasSuffix(n, ".vuka")) {
				continue
			}
			if src, err := read(filepath.Join(path, n)); err == nil && mainPkg.Match(src) {
				out = append(out, path)
				break
			}
		}
		return nil
	})
	return out
}

var mainPkg = regexp.MustCompile(`(?m)^package main\b`)

// scanRouteTree is the page packages of the pages/ directory beside main,
// the module's for "": nil when there is none.
func scanRouteTree(root, modPath, main string, read load.ReadFunc) *routeTree {
	dir := root
	if main != "" {
		dir = main
	}
	base := filepath.Join(dir, pagesDirName)
	if fi, err := os.Stat(base); err != nil || !fi.IsDir() {
		return nil
	}
	rel, _ := filepath.Rel(root, base)
	t := &routeTree{root: root, modPath: modPath, pages: base, pagesPath: modPath + "/" + filepath.ToSlash(rel), main: main, registered: map[string]bool{}}
	t.declared = declaredRoutes(dir, t.registered)
	filepath.WalkDir(base, func(path string, e fs.DirEntry, err error) error {
		if err != nil || !e.IsDir() {
			return nil
		}
		// A folder named _x is private, no routes below it, and param_id
		// beside [id] that folder's Go name: the generated files vuka gen
		// -inplace writes.
		if n := e.Name(); path != base && strings.HasPrefix(n, "_") && !load.IsGoName(path) {
			return filepath.SkipDir // no routes; its Vuka source is a package all the same
		}
		if n := e.Name(); path != base && (strings.HasPrefix(n, ".") || n == "testdata" || n == "vendor" ||
			n == "node_modules" || fileExists(filepath.Join(path, "go.mod")) || path == t.urlsDir() || load.IsGoName(path)) {
			return filepath.SkipDir
		}
		if d := readRouteDir(t, path, read); d != nil {
			t.dirs = append(t.dirs, d)
		}
		return nil
	})
	t.checkNames()
	return t
}

// urlsDir is the directory of the generated package urls.
func (t *routeTree) urlsDir() string { return filepath.Join(t.pages, urlsDirName) }

func readRouteDir(t *routeTree, dir string, read load.ReadFunc) *routeDir {
	root, registered := t.root, t.registered
	entries, err := os.ReadDir(dir)
	if err != nil {
		return nil
	}
	rel, _ := filepath.Rel(t.pages, dir)
	rel = filepath.ToSlash(rel)
	if rel == "." {
		rel = ""
	}
	d := &routeDir{dir: dir, rel: rel, goDir: load.GoDir(root, dir), importPath: t.pagesPath, bracket: map[string]string{}, fileOf: map[string]string{}, files: map[string]string{}}
	if rel != "" {
		d.importPath += "/" + load.GoRel(rel)
	}
	inBracket := strings.ContainsAny(rel, "[(")
	ctors := map[string]bool{}
	types, others := map[string]bool{}, map[string]diag.Span{} // declared types; other declared names, where
	structs, looks := map[string]bool{}, map[string]bool{}
	templates := map[string]string{}     // template-only page → its file
	funcFiles := map[string][]string{}   // a method func → the files declaring it
	goRendered := map[string]diag.Span{} // a type rendered by a Render or View of a .go or .vuka file → where
	for _, e := range entries {
		n := e.Name()
		path := filepath.Join(dir, n)
		if !e.IsDir() && validBracket(fileSeg(n)) {
			d.files[fileSeg(n)] = n
		}
		if !e.IsDir() && (n == routesGoName || n == pagesGoName && rel == "") {
			d.clashes = append(d.clashes, *diag.New("E0718", "%s is what vuka 1 generated for the folder routes, and pages/route.go registers them now", n).At(diag.Span{File: path, Line: 1}).
				WithHelp("delete %s: vuka generates pages/route.go, and a page without a constructor needs none of its own", n))
			continue
		}
		if !e.IsDir() && n == routeGoName && rel == "" {
			if src, err := read(path); err == nil && !bytes.HasPrefix(src, []byte("// Code generated by vuka")) {
				d.clashes = append(d.clashes, *diag.New("E0718", "pages/route.go is vuka's, the routes of the folders under pages/, and this one is written by hand").At(diag.Span{File: path, Line: 1}).
					WithHelp("rename the file: vuka writes pages/route.go"))
			}
			continue
		}
		if e.IsDir() || strings.Contains(n, "_test.") {
			continue
		}
		vukaSrc := strings.HasSuffix(n, ".vuka") || strings.HasSuffix(n, ".vuka.html") || strings.HasSuffix(n, ".templ")
		if !vukaSrc && !strings.HasSuffix(n, ".go") {
			continue
		}
		seg := fileSeg(n)
		if strings.ContainsAny(seg, "()") {
			d.clashes = append(d.clashes, *diag.New("E0723", "%s: a file can't be a route group, only a folder", n).At(diag.Span{File: path, Line: 1}).
				WithHelp("make (name) a folder and put the pages in it, or name the file without parentheses"))
			continue
		}
		if strings.HasSuffix(n, ".go") && strings.ContainsAny(n, "[]") {
			d.clashes = append(d.clashes, *diag.New("E0716", "%s is Go in a file named for a parameter, which the go command can't build", n).At(diag.Span{File: path, Line: 1}).
				WithHelp("write it as %s: Go names no [x] file, so vuka compiles it", strings.TrimSuffix(n, ".go")+".vuka"))
			continue
		}
		if strings.ContainsAny(seg, "[]") && !validBracket(seg) {
			d.clashes = append(d.clashes, *diag.New("E0704", "%s: %s names no path parameter", n, seg).At(diag.Span{File: path, Line: 1}).
				WithHelp("bracket a Go identifier, [id], or [path...] for the rest of the path"))
			continue
		}
		src, err := read(path)
		if err != nil {
			continue
		}
		if strings.HasSuffix(n, ".go") {
			if ok, _ := build.Default.MatchFile(dir, n); !ok {
				continue
			}
			if generatedFor(n, entries) {
				continue // its source's, read as the source
			}
			d.goFiles = append(d.goFiles, n)
		}
		d.vuka = d.vuka || vukaSrc
		if d.name == "" {
			d.name = packageName(n, src)
		} else if name := packageName(n, src); inBracket && strings.HasSuffix(n, ".go") && name != d.name && name != d.name+"_test" {
			// Copied into the folder's Go name, it would be a second package there.
			d.clashes = append(d.clashes, *diag.New("E0716", "%s is package %s, and the folder's other files are package %s", n, name, d.name).At(diag.Span{File: path, Line: 1}).
				WithHelp("write package %s: the go command sees the folder as %s, one package", d.name, filepath.Base(d.goDir)))
			continue
		}
		if strings.HasSuffix(n, ".vuka.html") {
			if n == "layout.vuka.html" {
				d.oldLayout = n
			}
			// A file in the 2.0 shape declares the struct it renders: a
			// page as a .go file's would be.
			sh, _ := transpile.ParseShape(src)
			switch {
			case n == "_layout.vuka.html":
				d.layout, d.layoutFile = "Layout", n
				if sh != nil {
					d.layout = sh.Type
					types[sh.Type] = true
				}
				continue
			case strings.HasPrefix(n, "_"):
				if sh != nil {
					types[sh.Type] = true
				}
				continue
			case sh != nil:
				types[sh.Type] = true
				if token.IsExported(sh.Type) && !sh.Generic {
					structs[sh.Type], looks[sh.Type] = true, true
					d.fileOf[sh.Type] = n
					if load.Bracketed(seg) {
						d.bracket[sh.Type] = seg
					}
				}
				continue
			case load.Bracketed(seg):
				if _, ok := templatePage("page.vuka.html", src); ok {
					d.clashes = append(d.clashes, *diag.New("E0711", "%s is a page at the parameter %s and declares no struct to bind it", n, seg).At(diag.Span{File: path, Line: 1}).
						WithHelp("declare the page's struct above its markup, with a field for the parameter: type Page struct { %s int }", goIdent(bracketName(seg))))
				}
				continue
			}
			if name, ok := templatePage(n, src); ok {
				templates[name] = n
			}
			continue
		}
		before := maps.Clone(types)
		topLevel(path, src, types, others, structs, looks)
		for _, m := range renderMethod.FindAllSubmatchIndex(src, -1) {
			goRendered[string(src[m[2]:m[3]])] = diag.Span{File: path, Line: bytes.Count(src[:m[0]], []byte("\n")) + 1}
		}
		if load.Bracketed(seg) {
			for name := range types {
				if !before[name] {
					d.bracket[name] = seg
				}
			}
		}
		if strings.HasSuffix(n, ".vuka") {
			for _, m := range typeDecl.FindAllSubmatchIndex(src, -1) {
				for _, a := range attrsAbove(src, m[0]) {
					if routeAttr.MatchString(a) {
						registered[d.importPath+"."+string(src[m[2]:m[3]])] = true
					}
				}
			}
		}
		for _, m := range methodDecl.FindAllSubmatch(src, -1) {
			funcFiles[string(m[2])] = append(funcFiles[string(m[2])], n)
		}
		for _, m := range ctorDecl.FindAllSubmatch(src, -1) {
			ctors[string(m[1])] = true
		}
	}
	if len(d.clashes) > 0 {
		return d
	}
	if d.name == "" || d.name == "main" || len(d.goFiles) == 0 && !d.vuka {
		return nil
	}
	for _, method := range slices.Sorted(maps.Keys(funcFiles)) {
		files := funcFiles[method]
		var goFiles []string
		for _, f := range files {
			if strings.HasSuffix(f, ".go") {
				goFiles = append(goFiles, f)
			}
		}
		if len(goFiles) > 1 {
			d.clashes = append(d.clashes, *diag.New("E0717", "%s and %s both declare %s, and are Go: a method func is its file's route", goFiles[0], goFiles[1], method).
				At(diag.Span{File: filepath.Join(dir, goFiles[1]), Line: 1}).WithRelated(diag.Span{File: filepath.Join(dir, goFiles[0]), Line: 1}).
				WithHelp("write them as .vuka files, whose method funcs vuka keeps apart, or join the two routes' files"))
			continue
		}
		for _, f := range files {
			goName := method
			if len(files) > 1 && strings.HasSuffix(f, ".vuka") {
				goName = method + "_" + fileKey(f)
			}
			d.funcs = append(d.funcs, methodFunc{method: method, goName: goName, file: f})
		}
	}
	for _, name := range slices.Sorted(maps.Keys(templates)) {
		if types[name] {
			continue // its struct is in a .go or .vuka file
		}
		d.clashes = append(d.clashes, *diag.New("E0719", "%s is a page whose struct, %s, is declared nowhere", templates[name], name).At(diag.Span{File: filepath.Join(dir, templates[name]), Line: 1}).
			WithHelp("declare it above the markup: type %s struct{}", name))
	}
	for _, name := range slices.Sorted(maps.Keys(structs)) {
		if looks[name] && !registered[name] && !registered[d.importPath+"."+name] {
			ctors[name] = true
		}
	}
	for name := range ctors {
		if !d.notPage(name) {
			d.pages = append(d.pages, name)
		}
	}
	for _, name := range slices.Sorted(maps.Keys(goRendered)) {
		if ctors[name] && !d.notPage(name) && !registered[d.importPath+"."+name] {
			d.clashes = append(d.clashes, *diag.New("E0721", "%s is a page whose markup is written in Go: a page is a .vuka.html file", name).At(goRendered[name]).
				WithHelp("move %s to %s.vuka.html: the struct and its methods above, the markup below, in place of its Render or View", name, strings.TrimSuffix(strings.TrimSuffix(filepath.Base(goRendered[name].File), ".go"), ".vuka")))
		}
	}
	slices.Sort(d.pages)
	return d
}

// notPage reports whether the type name is no page of d's whatever it
// looks like: its layout, Guard, and the 1.x Layout and Params.
func (d *routeDir) notPage(name string) bool {
	return name == d.layout || name == "Layout" || name == "Params" || name == "Guard"
}

// urlName is how a page of d is named: by the .vuka.html file declaring it
// (new.vuka.html is New, whatever its struct's name), else by its type; a
// [id] file's page is its parameter.
func (d *routeDir) urlName(typ string) string {
	if b := d.bracket[typ]; b != "" {
		return b
	}
	if f := d.fileOf[typ]; f != "" {
		if seg := fileSeg(f); seg != "" {
			return componentName(f)
		}
		return "Index"
	}
	return typ
}

// componentName is the type a template file names: team-settings.vuka.html
// is TeamSettings.
func componentName(file string) string {
	var b strings.Builder
	for _, part := range strings.FieldsFunc(strings.TrimSuffix(file, ".vuka.html"), func(r rune) bool { return r == '-' || r == '_' || r == '.' }) {
		b.WriteString(upperFirst(part))
	}
	return b.String()
}

// fileKey is a file's name as a part of an identifier: [id].vuka is id,
// list-all.vuka list_all.
func fileKey(file string) string {
	base := strings.TrimSuffix(strings.TrimSuffix(file, ".vuka"), ".go")
	base = strings.TrimSuffix(strings.TrimPrefix(strings.TrimSuffix(base, "]"), "["), "...")
	return strings.Map(func(r rune) rune {
		if r == '_' || unicode.IsLetter(r) || unicode.IsDigit(r) {
			return r
		}
		return '_'
	}, base)
}

// validBracket reports whether a name is a path parameter's: a Go
// identifier in brackets, [id], or [path...] for the rest of the path.
func validBracket(name string) bool {
	return load.Bracketed(name) && token.IsIdentifier(bracketName(name))
}

// bracketName is the parameter a bracketed name binds: id for [id] and
// [id...].
func bracketName(name string) string {
	return strings.TrimSuffix(strings.TrimSuffix(strings.TrimPrefix(name, "["), "]"), "...")
}

// isRest reports whether a bracketed name takes the rest of the path.
func isRest(name string) bool { return strings.HasSuffix(name, "...]") }

// validGroup reports whether a folder name is a route group's: a Go
// identifier in parentheses, (admin).
func validGroup(name string) bool {
	return load.Grouped(name) && token.IsIdentifier(name[1:len(name)-1])
}

// urlRel is a slash path from pages/ as the URL sees it: its route groups
// left out, (admin)/users is users.
func urlRel(rel string) string {
	if !strings.Contains(rel, "(") {
		return rel
	}
	var out []string
	for _, p := range strings.Split(rel, "/") {
		if !load.Grouped(p) {
			out = append(out, p)
		}
	}
	return strings.Join(out, "/")
}

// checkNames reports the folders whose bracketed names name no parameter,
// or a parameter bound above already, and those in parentheses that name
// no route group.
func (t *routeTree) checkNames() {
	seen := map[string]bool{}
	for _, d := range t.dirs {
		if d.rel == "" {
			continue
		}
		parts := strings.Split(d.rel, "/")
		bound := map[string]string{}
		for i, p := range parts {
			at := strings.Join(parts[:i+1], "/")
			bad, code, help := "", diag.Code("E0704"), "bracket a Go identifier, [id], or [path...] for the rest of the path, each parameter once in a path"
			switch {
			case strings.ContainsAny(p, "()") && !validGroup(p):
				bad, code, help = fmt.Sprintf("the folder %s names no route group", p), "E0723", "name a route group with a Go identifier in parentheses: (admin)"
			case strings.ContainsAny(p, "[]") && !validBracket(p):
				bad = fmt.Sprintf("the folder %s names no path parameter", p)
			case load.Bracketed(p):
				name := strings.ToLower(bracketName(p))
				if above, ok := bound[name]; ok {
					bad = fmt.Sprintf("the parameter %s is bound above already, by %s", p, above)
				}
				bound[name] = at
			}
			if bad != "" && !seen[at] {
				seen[at] = true
				d.clashes = append(d.clashes, *diag.New(code, "pages/%s: %s", at, bad).At(diag.Span{File: filepath.Join(t.pages, filepath.FromSlash(at))}).
					WithHelp("%s", help))
			}
		}
		for _, b := range slices.Sorted(maps.Keys(d.files)) {
			if _, ok := bound[strings.ToLower(bracketName(b))]; ok && !seen[d.rel+"/"+b] {
				seen[d.rel+"/"+b] = true
				d.clashes = append(d.clashes, *diag.New("E0704", "pages/%s/%s: the parameter %s is bound above already", d.rel, b, b).At(diag.Span{File: filepath.Join(d.dir, b)}).
					WithHelp("name the parameter for what it binds here"))
			}
		}
	}
}

// generatedFor reports whether a .go file is the Go generated for a source
// beside it (x_vuka.go, x_html.go, x_templ.go): the transpile brings its own.
func generatedFor(name string, entries []fs.DirEntry) bool {
	for _, e := range entries {
		n := e.Name()
		if (strings.HasSuffix(n, ".vuka") || strings.HasSuffix(n, ".vuka.html")) && transpile.GoName(n) == name ||
			strings.HasSuffix(n, ".templ") && load.TemplGoName(n) == name || name == transpile.CallsGoName {
			return true
		}
	}
	return false
}

// packageName is the name a source file's package clause gives.
func packageName(name string, src []byte) string {
	if strings.HasSuffix(name, ".vuka.html") {
		return transpile.ParseTemplateHead(src).Package
	}
	f, err := parser.ParseFile(token.NewFileSet(), name, src, parser.PackageClauseOnly)
	if err != nil || f.Name == nil {
		return ""
	}
	return f.Name.Name
}

// routeStubs are the stub files the transpile puts in the overlay after
// each package (load.AfterPackage), by directory and target: they replace
// any written to disk earlier, for the packages importing them too.
var routeStubs = map[string][]load.Generated{}

// stub readies pkgs for the transpile: the package urls, as a stub with
// every name a page could use (its paths' types taking ...any), and the
// package pages with a stub route.go, func Routes() registering nothing, so
// a main of Vuka source calling pages.Routes() transpiles; a package of Go
// alone is made a Vuka package for it, by a placeholder .vuka file. A .vuka
// file sharing a method func's name with another file of its package has
// its declaration renamed (GET of [id].vuka is GET_id). Its error is what
// the scan found that would derail the transpile.
func (t *routeTree) stub(pkgs []*load.Package) ([]*load.Package, error) {
	clashes := diag.List(slices.Clone(t.clashes))
	for _, d := range t.dirs {
		clashes = append(clashes, d.clashes...)
	}
	if len(clashes) > 0 {
		return pkgs, clashes
	}
	pagesDir := t.pages
	if !slices.ContainsFunc(t.dirs, func(d *routeDir) bool { return len(d.pages) > 0 || len(d.funcs) > 0 }) &&
		!fileExists(filepath.Join(t.urlsDir(), urlsGoName)) && !fileExists(filepath.Join(pagesDir, routeGoName)) {
		return pkgs, nil
	}
	pkg := func(dir, goDir, importPath, name string, goFiles []string) *load.Package {
		i := slices.IndexFunc(pkgs, func(p *load.Package) bool { return realPathOf(p.Dir) == dir && p.Name == name })
		if i >= 0 {
			return pkgs[i]
		}
		p := &load.Package{Dir: dir, ImportPath: importPath, Name: name}
		if goDir != dir {
			p.GoDir = goDir
		}
		for _, n := range goFiles {
			src, err := os.ReadFile(filepath.Join(dir, n))
			if err != nil {
				continue
			}
			p.Files = append(p.Files, transpile.File{Name: n, Src: src})
			if f, err := parser.ParseFile(token.NewFileSet(), n, src, parser.ImportsOnly); err == nil {
				for _, imp := range f.Imports {
					if path, err := strconv.Unquote(imp.Path.Value); err == nil {
						p.Imports = append(p.Imports, path)
					}
				}
			}
		}
		pkgs = append(pkgs, p)
		return p
	}
	// The placeholder names the stub's content, so a cached transpile of
	// the package is reused only for the same stub.
	placeholder := func(p *load.Package, stub []byte) {
		if !slices.ContainsFunc(p.Files, func(f transpile.File) bool { return f.IsVuka() }) {
			p.Files = append(p.Files, transpile.File{Name: routesStub, Src: fmt.Appendf(nil, "package %s\n\n// %x\n", p.Name, sha256.Sum256(stub))})
		}
	}
	if err := os.MkdirAll(t.urlsDir(), 0o755); err != nil {
		return nil, err
	}
	if err := t.goDirs(); err != nil {
		return nil, err
	}
	urls := t.urlsStub()
	up := pkg(t.urlsDir(), t.urlsDir(), t.pagesPath+"/"+urlsDirName, urlsDirName, nil)
	placeholder(up, urls)
	routeStubs[up.Dir] = []load.Generated{{Target: filepath.Join(up.Dir, urlsGoName), Src: urls}}
	root := t.root0()
	rp := pkg(pagesDir, pagesDir, t.pagesPath, root.name, root.goFiles)
	rp.Files = slices.DeleteFunc(rp.Files, func(f transpile.File) bool { return f.Name == routeGoName })
	stub := []byte(routesHeading + "package " + root.name + "\n\nimport \"" + webPath + "\"\n\n// Routes registers the pages under pages/.\nfunc Routes() web.Option { return web.OptionFunc(func(*web.App) {}) }\n")
	placeholder(rp, stub)
	routeStubs[pagesDir] = []load.Generated{{Target: filepath.Join(pagesDir, routeGoName), Src: stub}}
	for _, d := range t.dirs {
		if !slices.ContainsFunc(d.funcs, func(f methodFunc) bool { return f.goName != f.method }) {
			continue
		}
		p := pkg(d.dir, d.goDir, d.importPath, d.name, d.goFiles)
		// Files declaring one method func alike, each its route: the
		// function of a .vuka file is renamed for it.
		for _, mf := range d.funcs {
			if mf.goName == mf.method {
				continue
			}
			for i, f := range p.Files {
				if f.Name == mf.file {
					p.Files[i] = transpile.File{Name: f.Name, Src: renameMethodFunc(f.Src, mf.method, mf.goName)}
				}
			}
		}
	}
	return pkgs, nil
}

// goDirs tidies the directories the go command sees bracketed, grouped and
// private folders' packages in, param_id for [id], group_admin for (admin),
// private_parts for _parts: they live in the overlay alone (or on disk where
// vuka gen -inplace writes them), so one left empty is removed, and so is
// one whose source folder is gone holding nothing but generated Go.
func (t *routeTree) goDirs() error {
	var stale []string
	filepath.WalkDir(t.pages, func(path string, e fs.DirEntry, err error) error {
		if err != nil || !e.IsDir() || !strings.HasPrefix(e.Name(), "param_") && !strings.HasPrefix(e.Name(), "group_") && !strings.HasPrefix(e.Name(), "private_") {
			return nil
		}
		if emptyTree(path) || !load.IsGoName(path) && generatedOnly(path) {
			stale = append(stale, path)
		}
		return filepath.SkipDir
	})
	for _, dir := range stale {
		if err := os.RemoveAll(dir); err != nil {
			return err
		}
	}
	return nil
}

// emptyTree reports whether dir and the directories below it hold no file.
func emptyTree(dir string) bool {
	empty := true
	filepath.WalkDir(dir, func(path string, e fs.DirEntry, err error) error {
		if err != nil || !e.IsDir() {
			empty = false
			return filepath.SkipAll
		}
		return nil
	})
	return empty
}

// generatedOnly reports whether the files below dir are all generated Go.
func generatedOnly(dir string) bool {
	only := true
	filepath.WalkDir(dir, func(path string, e fs.DirEntry, err error) error {
		if err != nil || !only || e.IsDir() {
			return err
		}
		src, err := os.ReadFile(path)
		first, _, _ := bytes.Cut(src, []byte("\n"))
		if err != nil || !strings.HasSuffix(path, ".go") || !generatedHeader.Match(first) {
			only = false
		}
		return nil
	})
	return only
}

var generatedHeader = regexp.MustCompile(`^// Code generated .* DO NOT EDIT\.$`)

// root0 is the folder pages/, a routeDir when it holds no source.
func (t *routeTree) root0() *routeDir {
	for _, d := range t.dirs {
		if d.rel == "" {
			return d
		}
	}
	return &routeDir{dir: t.pages, goDir: t.pages, name: pagesDirName, importPath: t.pagesPath}
}

// stubbed reports whether a generated file is a stub or a placeholder's.
func stubbed(g load.Generated) bool {
	if filepath.Base(g.Target) == transpile.GoName(routesStub) {
		return true
	}
	return slices.ContainsFunc(routeStubs[filepath.Dir(g.Target)], func(s load.Generated) bool { return s.Target == g.Target && bytes.Equal(s.Src, g.Src) })
}

// routesResult is what finishing the folder routes gives: the route table,
// its files, and the problems found.
type routesResult struct {
	routes []*folderRoute
	files  []load.Generated
	diags  []diag.Diagnostic
}

// err is the result's errors, nil when it has none.
func (r *routesResult) err() error {
	var l diag.List
	for _, d := range r.diags {
		if d.Severity == diag.Error {
			l = append(l, d)
		}
	}
	if len(l) == 0 {
		return nil
	}
	return l
}

// finish builds the route tables from the transpiled module (gens, through
// overlay), and returns gens and the overlay with the stubs replaced by the
// generated files, with the tables in one result. With errors in a tree,
// its stubs are dropped and nothing added for it.
func (ts routeTrees) finish(gens []load.Generated, overlay, tmp string) ([]load.Generated, string, *routesResult, error) {
	res := &routesResult{}
	if len(ts) == 0 {
		return gens, overlay, res, nil
	}
	var drop []string
	for _, g := range gens {
		if stubbed(g) {
			drop = append(drop, g.Target)
		}
	}
	gens = withoutStubs(gens)
	ov, err := readOverlay(overlay)
	if err != nil {
		return nil, "", nil, err
	}
	for _, t := range ts {
		r := &routesResult{}
		t.result = r
		t.check(ov, overlay, r)
		if r.err() == nil {
			r.files = t.generate(r.routes)
		}
		res.routes = append(res.routes, r.routes...)
		res.files = append(res.files, r.files...)
		res.diags = append(res.diags, r.diags...)
	}
	if len(drop) == 0 && len(res.files) == 0 {
		return gens, overlay, res, nil
	}
	if overlay == "" {
		overlay = filepath.Join(tmp, "overlay.json")
	}
	for _, target := range drop {
		delete(ov, target)
	}
	for i, g := range res.files {
		file := filepath.Join(tmp, fmt.Sprintf("routes%d_%s", i, filepath.Base(g.Target)))
		if err := os.WriteFile(file, g.Src, 0o644); err != nil {
			return nil, "", nil, err
		}
		ov[g.Target] = file
	}
	data, err := json.Marshal(struct{ Replace map[string]string }{ov})
	if err != nil {
		return nil, "", nil, err
	}
	if err := os.WriteFile(overlay, data, 0o644); err != nil {
		return nil, "", nil, err
	}
	return append(gens, res.files...), overlay, res, nil
}

// withoutStubs is gens without the stubs and placeholders' files.
func withoutStubs(gens []load.Generated) []load.Generated {
	return slices.DeleteFunc(slices.Clone(gens), stubbed)
}

// readOverlay is an overlay file's replacements; none for "".
func readOverlay(path string) (map[string]string, error) {
	ov := struct{ Replace map[string]string }{map[string]string{}}
	if path == "" {
		return ov.Replace, nil
	}
	data, err := os.ReadFile(path)
	if err != nil {
		return nil, err
	}
	if err := json.Unmarshal(data, &ov); err != nil {
		return nil, err
	}
	if ov.Replace == nil {
		ov.Replace = map[string]string{}
	}
	return ov.Replace, nil
}

// overlayContext is the build context seeing the files of an overlay as
// the go command does.
func overlayContext(ov map[string]string) *build.Context {
	ctx := build.Default
	ctx.ReadDir = func(dir string) ([]fs.FileInfo, error) {
		entries, err := os.ReadDir(dir)
		if err != nil && (!errors.Is(err, fs.ErrNotExist) || !slices.ContainsFunc(slices.Collect(maps.Keys(ov)), func(t string) bool { return filepath.Dir(t) == dir })) {
			return nil, err
		}
		var infos []fs.FileInfo
		have := map[string]bool{}
		for _, e := range entries {
			p := filepath.Join(dir, e.Name())
			have[e.Name()] = true
			if r, ok := ov[p]; ok {
				if r == "" {
					continue
				}
				if fi, err := os.Stat(r); err == nil {
					infos = append(infos, overlaidInfo{fi, e.Name()})
				}
				continue
			}
			if fi, err := e.Info(); err == nil {
				infos = append(infos, fi)
			}
		}
		for target, r := range ov {
			if filepath.Dir(target) == dir && !have[filepath.Base(target)] && r != "" {
				if fi, err := os.Stat(r); err == nil {
					infos = append(infos, overlaidInfo{fi, filepath.Base(target)})
				}
			}
		}
		slices.SortFunc(infos, func(a, b fs.FileInfo) int { return strings.Compare(a.Name(), b.Name()) })
		return infos, nil
	}
	// A [id] folder's package is in its Go name's directory, which only
	// the overlay holds.
	ctx.IsDir = func(path string) bool {
		if fi, err := os.Stat(path); err == nil {
			return fi.IsDir()
		}
		for target := range ov {
			if strings.HasPrefix(target, path+string(filepath.Separator)) {
				return true
			}
		}
		return false
	}
	ctx.OpenFile = func(path string) (io.ReadCloser, error) {
		if r, ok := ov[path]; ok {
			if r == "" {
				return nil, os.ErrNotExist
			}
			path = r
		}
		return os.Open(path)
	}
	return &ctx
}

// overlaidInfo is an overlay file's info under the name it replaces.
type overlaidInfo struct {
	fs.FileInfo
	name string
}

func (i overlaidInfo) Name() string { return i.name }

// templatePage is the type a .vuka.html file's template renders, when the
// file has markup of its own (not only partials): about.vuka.html and
// terms-of-service.vuka.html render About and TermsOfService.
func templatePage(name string, src []byte) (string, bool) {
	inImports := false
	for _, line := range strings.Split(string(src), "\n") {
		l := strings.TrimSpace(line)
		switch {
		case l == "" || strings.HasPrefix(l, "//") || strings.HasPrefix(l, "package "):
			continue
		case inImports:
			inImports = l != ")"
			continue
		case strings.HasPrefix(l, "import"):
			inImports = strings.HasSuffix(l, "(")
			continue
		case strings.HasPrefix(l, "func ") || strings.HasPrefix(l, "<script") || strings.HasPrefix(l, "<style"):
			return "", false
		}
		break
	}
	var b strings.Builder
	for _, part := range strings.FieldsFunc(strings.TrimSuffix(name, ".vuka.html"), func(r rune) bool { return r == '-' || r == '_' || r == '.' }) {
		b.WriteString(upperFirst(part))
	}
	n := b.String()
	return n, token.IsIdentifier(n) && token.IsExported(n)
}

// topLevel records the names a Go or Vuka file declares at the top level:
// types in types, other names (functions, variables, constants) in others,
// the exported struct types, not generic, in structs, and in looks the
// types looking like a page or an endpoint: a struct with an embedded
// field, a type of Vuka source, or one with a Render, View, Get, Post, Put,
// Patch or Delete method.
func topLevel(path string, src []byte, types map[string]bool, others map[string]diag.Span, structs, looks map[string]bool) {
	if strings.HasSuffix(path, ".go") {
		fset := token.NewFileSet()
		f, _ := parser.ParseFile(fset, path, src, parser.SkipObjectResolution)
		if f == nil {
			return
		}
		for _, decl := range f.Decls {
			switch d := decl.(type) {
			case *ast.FuncDecl:
				if d.Recv == nil {
					p := fset.Position(d.Name.Pos())
					others[d.Name.Name] = diag.Span{File: path, Line: p.Line, Col: p.Column}
				} else if len(d.Recv.List) == 1 && slices.Contains(routeLooks, d.Name.Name) {
					if name := recvName(d); name != "" {
						looks[name] = true
					}
				}
			case *ast.GenDecl:
				for _, spec := range d.Specs {
					switch sp := spec.(type) {
					case *ast.TypeSpec:
						types[sp.Name.Name] = true
						if st, ok := sp.Type.(*ast.StructType); ok && sp.Name.IsExported() && sp.TypeParams == nil && !sp.Assign.IsValid() {
							structs[sp.Name.Name] = true
							if slices.ContainsFunc(st.Fields.List, func(f *ast.Field) bool { return len(f.Names) == 0 }) {
								looks[sp.Name.Name] = true
							}
						}
					case *ast.ValueSpec:
						for _, id := range sp.Names {
							p := fset.Position(id.Pos())
							others[id.Name] = diag.Span{File: path, Line: p.Line, Col: p.Column}
						}
					}
				}
			}
		}
		return
	}
	for _, m := range typeDecl.FindAllSubmatch(src, -1) {
		types[string(m[1])] = true
	}
	for _, m := range structDecl.FindAllSubmatchIndex(src, -1) {
		name := string(src[m[2]:m[3]])
		structs[name] = true
		if slices.ContainsFunc(attrsAbove(src, m[0]), func(a string) bool { return strings.HasPrefix(a, "ui.Island") }) {
			looks[name] = true // a page backed by its component
		}
	}
	for _, m := range looksMethod.FindAllSubmatch(src, -1) {
		looks[string(m[1])] = true
	}
	for _, m := range topFunc.FindAllSubmatchIndex(src, -1) {
		others[string(src[m[2]:m[3]])] = diag.Span{File: path, Line: bytes.Count(src[:m[2]], []byte("\n")) + 1}
	}
}

// routeLooks are the methods that make a type look like a page or an
// endpoint before its package is type-checked.
var routeLooks = []string{"Render", "View", "Get", "Post", "Put", "Patch", "Delete"}

// looksMethod is a .vuka file's declaration of one of routeLooks.
var looksMethod = regexp.MustCompile(`(?m)^func\s*\(\s*\w*\s*\*?\s*([A-Z]\w*)\s*\)\s*(?:` + strings.Join(routeLooks, "|") + `)\s*\(`)

// renameMethodFunc renames the declaration of the method func method in
// src, keeping the file's lines and every other name.
func renameMethodFunc(src []byte, method, goName string) []byte {
	return methodDecl.ReplaceAllFunc(src, func(m []byte) []byte {
		if sub := methodDecl.FindSubmatch(m); string(sub[2]) == method {
			return []byte("func" + string(sub[1]) + goName + string(sub[3]))
		}
		return m
	})
}
