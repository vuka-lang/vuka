// Folder routes: the module's pages/ directory is a tree of packages whose
// folder path is the URL. Each page package gets routes_gen.go, its pages'
// typed URL functions (EditURL), and pages/pages_gen.go registers every
// page, its method handlers and its layouts with web.Routes, so a page
// package importing its parent (for a link) never forms a cycle with the
// parent's layout.
//
// The URL functions are what page code calls, so they must exist while the
// packages are transpiled, before their types are known: each page package
// is transpiled with a stub (vuka_routes_stub.vuka) declaring every URL
// function its sources could need as func(...any) string. Once the module
// is transpiled, the page packages are type-checked from the overlay, the
// route table is built from their types, and the real files replace the
// stubs in the overlay. A template-only page (about.vuka.html, its type
// About declared nowhere) gets its type and constructor in the stub, and
// then in routes_gen.go, so its template compiles as the type's Render.

const (
	pagesDirName  = "pages"
	routesGoName  = "routes_gen.go"
	pagesGoName   = "pages_gen.go"
	routesStub    = "vuka_routes_stub.vuka"
	routesHeading = "// Code generated by vuka from the folders under pages/. DO NOT EDIT.\n\n"
)

// routeTree is the page packages under a module's pages/ directory.
type routeTree struct {
	root, modPath string
	dirs          []*routeDir     // by rel, parents first
	declared      []declaredRoute // the routes the module declares itself
	// registered are the types registered as pages another way, by a
	// decorator on the type (by import path and name) or a call naming
	// their constructor (by name): not folder pages.
	registered map[string]bool
	info       map[*routeDir]*dirInfo
	result     *routesResult // the last finish's
}

// apply is finish, failing on the route table's errors.
func (t *routeTree) apply(gens []load.Generated, overlay, tmp string) ([]load.Generated, string, error) {
	gens, overlay, res, err := t.finish(gens, overlay, tmp)
	if err != nil {
		return nil, "", err
	}
	return gens, overlay, res.err()
}

// files are the files the last finish generated.
func (t *routeTree) files() []load.Generated {
	if t == nil || t.result == nil {
		return nil
	}
	return t.result.files
}

// routeDir is one directory under pages/ holding Go or Vuka source.
type routeDir struct {
	dir, rel      string // rel: slash path from pages/ ("" for pages/ itself)
	importPath    string
	name          string   // the package's name
	stubs         []string // the URL functions its stub declares
	goFiles       []string // its .go files, when it has no Vuka source
	templates     []string // its template-only pages
	templateFiles []string // their files
	stubTypes     []string // those the stub declares (not a routes_gen.go on disk)
	params        bool     // it declares Params
	clashes       []diag.Diagnostic
	vuka          bool // it has .vuka, .vuka.html or .templ files
}

var (
	ctorDecl   = regexp.MustCompile(`(?m)^func\s+New([A-Z]\w*)\s*[\[(]`)
	urlFuncDec = regexp.MustCompile(`(?m)^func\s+([A-Z]\w*URL)\s*[\[(]`)
	typeDecl   = regexp.MustCompile(`(?m)^type\s+([A-Z]\w*)\s`)
	topFunc    = regexp.MustCompile(`(?m)^(?:func|var|const)\s+([A-Z]\w*)\b`)
	routeAttr  = regexp.MustCompile(`^\w+\.(Get|Post|Put|Patch|Delete|Handle|Live)$`)
)

// scanRoutes finds the page packages of the module at root: nil when it has
// no pages/ directory. read reads a source (the editor's buffer, for the
// language server); nil reads the disk.
func scanRoutes(root, modPath string, read load.ReadFunc) *routeTree {
	if read == nil {
		read = os.ReadFile
	}
	root = realPathOf(root)
	base := filepath.Join(root, pagesDirName)
	if fi, err := os.Stat(base); err != nil || !fi.IsDir() {
		return nil
	}
	t := &routeTree{root: root, modPath: modPath, registered: map[string]bool{}}
	t.declared = declaredRoutes(root, t.registered)
	filepath.WalkDir(base, func(path string, e fs.DirEntry, err error) error {
		if err != nil || !e.IsDir() {
			return nil
		}
		if n := e.Name(); path != base && (strings.HasPrefix(n, ".") || strings.HasPrefix(n, "_") || n == "testdata" || n == "vendor" ||
			n == "node_modules" || fileExists(filepath.Join(path, "go.mod"))) {
			return filepath.SkipDir
		}
		if d := readRouteDir(root, modPath, path, read, t.registered); d != nil {
			t.dirs = append(t.dirs, d)
		}
		return nil
	})
	return t
}

func readRouteDir(root, modPath, dir string, read load.ReadFunc, registered map[string]bool) *routeDir {
	entries, err := os.ReadDir(dir)
	if err != nil {
		return nil
	}
	rel, _ := filepath.Rel(filepath.Join(root, pagesDirName), dir)
	rel = filepath.ToSlash(rel)
	if rel == "." {
		rel = ""
	}
	d := &routeDir{dir: dir, rel: rel, importPath: modPath + "/" + pagesDirName}
	if rel != "" {
		d.importPath += "/" + rel
	}
	ctors, declared := map[string]bool{}, map[string]bool{}
	types, others := map[string]bool{}, map[string]diag.Span{} // declared types; other declared names, where
	genTypes := map[string]bool{}                              // the types a routes_gen.go written earlier declares
	templates := map[string]string{}                           // template-only page → its file
	for _, e := range entries {
		n := e.Name()
		if e.IsDir() || strings.Contains(n, "_test.") {
			continue
		}
		vukaSrc := strings.HasSuffix(n, ".vuka") || strings.HasSuffix(n, ".vuka.html") || strings.HasSuffix(n, ".templ")
		if !vukaSrc && (!strings.HasSuffix(n, ".go") || n == pagesGoName && rel == "") {
			continue
		}
		src, err := read(filepath.Join(dir, n))
		if err != nil {
			continue
		}
		if strings.HasSuffix(n, ".go") {
			if ok, _ := build.Default.MatchFile(dir, n); !ok {
				continue
			}
			if !generatedFor(n, entries) {
				d.goFiles = append(d.goFiles, n)
			}
		}
		d.vuka = d.vuka || vukaSrc
		if d.name == "" {
			d.name = packageName(n, src)
		}
		if strings.HasSuffix(n, ".vuka.html") {
			if name, ok := templatePage(n, src); ok {
				templates[name] = n
			}
			continue
		}
		if n == routesGoName {
			topLevel(filepath.Join(dir, n), src, genTypes, map[string]diag.Span{})
		} else {
			topLevel(filepath.Join(dir, n), src, types, others)
		}
		if strings.HasSuffix(n, ".vuka") {
			for _, m := range typeDecl.FindAllSubmatchIndex(src, -1) {
				for _, a := range attrsAbove(src, m[0]) {
					if routeAttr.MatchString(a) {
						registered[d.importPath+"."+string(src[m[2]:m[3]])] = true
					}
				}
			}
		}
		for _, m := range ctorDecl.FindAllSubmatch(src, -1) {
			ctors[string(m[1])] = true
		}
		for _, m := range urlFuncDec.FindAllSubmatch(src, -1) {
			declared[string(m[1])] = true
		}
	}
	if d.name == "" || d.name == "main" || len(d.goFiles) == 0 && !d.vuka {
		return nil
	}
	d.params = types["Params"]
	for _, name := range slices.Sorted(maps.Keys(templates)) {
		file := templates[name]
		if types[name] || name == "Layout" || name == "Params" {
			continue
		}
		if at, ok := others[name]; ok {
			d.clashes = append(d.clashes, *diag.New("E0706", "%s is declared, and vuka declares the type %s for the template-only page %s", name, name, file).At(at).
				WithHelp("rename %s, or declare the page's type yourself: type %s struct{…}", name, name))
			continue
		}
		if at, ok := others["New"+name]; ok {
			d.clashes = append(d.clashes, *diag.New("E0706", "New%s is declared, and vuka declares it for the template-only page %s", name, file).At(at).
				WithHelp("declare the type %s yourself beside its constructor, or rename the function", name))
			continue
		}
		d.templates = append(d.templates, name)
		d.templateFiles = append(d.templateFiles, file)
		if !genTypes[name] {
			d.stubTypes = append(d.stubTypes, name)
		}
		ctors[name] = true
	}
	for name := range ctors {
		if name != "Layout" && name != "Params" && !declared[name+"URL"] {
			d.stubs = append(d.stubs, name+"URL")
		}
	}
	slices.Sort(d.stubs)
	return d
}

// generatedFor reports whether a .go file is the Go generated for a source
// beside it (x_vuka.go, x_html.go, x_templ.go): the transpile brings its own.
func generatedFor(name string, entries []fs.DirEntry) bool {
	for _, e := range entries {
		n := e.Name()
		if (strings.HasSuffix(n, ".vuka") || strings.HasSuffix(n, ".vuka.html")) && transpile.GoName(n) == name ||
			strings.HasSuffix(n, ".templ") && load.TemplGoName(n) == name || name == transpile.CallsGoName {
			return true
		}
	}
	return false
}

// packageName is the name a source file's package clause gives.
func packageName(name string, src []byte) string {
	if strings.HasSuffix(name, ".vuka.html") {
		return transpile.ParseTemplateHead(src).Package
	}
	f, err := parser.ParseFile(token.NewFileSet(), name, src, parser.PackageClauseOnly)
	if err != nil || f.Name == nil {
		return ""
	}
	return f.Name.Name
}

// stubSrc is the stub a page package is transpiled with.
func (d *routeDir) stubSrc() []byte {
	var b bytes.Buffer
	b.WriteString(routesHeading + "package " + d.name + "\n")
	b.WriteString(d.templateTypes(d.stubTypes))
	for _, name := range d.stubs {
		fmt.Fprintf(&b, "\nfunc %s(...any) string { return \"\" }\n", name)
	}
	return b.Bytes()
}

// stub adds each page package's stub to pkgs, a package of Go alone made a
// Vuka package for it, and leaves a pages_gen.go written earlier out of the
// pages package. Its error is the template-only pages whose names are
// taken, which the transpile would report as their templates' errors.
func (t *routeTree) stub(pkgs []*load.Package) ([]*load.Package, error) {
	if t == nil {
		return pkgs, nil
	}
	var clashes diag.List
	for _, d := range t.dirs {
		clashes = append(clashes, d.clashes...)
	}
	if len(clashes) > 0 {
		return pkgs, clashes
	}
	for _, d := range t.dirs {
		i := slices.IndexFunc(pkgs, func(p *load.Package) bool { return realPathOf(p.Dir) == d.dir && p.Name == d.name })
		if i < 0 && len(d.stubs) == 0 && len(d.stubTypes) == 0 {
			continue
		}
		if i < 0 {
			p := &load.Package{Dir: d.dir, ImportPath: d.importPath, Name: d.name}
			for _, n := range d.goFiles {
				src, err := os.ReadFile(filepath.Join(d.dir, n))
				if err != nil {
					continue
				}
				p.Files = append(p.Files, transpile.File{Name: n, Src: src})
				if f, err := parser.ParseFile(token.NewFileSet(), n, src, parser.ImportsOnly); err == nil {
					for _, imp := range f.Imports {
						if path, err := strconv.Unquote(imp.Path.Value); err == nil {
							p.Imports = append(p.Imports, path)
						}
					}
				}
			}
			pkgs = append(pkgs, p)
			i = len(pkgs) - 1
		}
		p := pkgs[i]
		if d.rel == "" {
			p.Files = slices.DeleteFunc(p.Files, func(f transpile.File) bool { return f.Name == pagesGoName })
		}
		if len(d.stubs) > 0 || len(d.stubTypes) > 0 {
			p.Files = append(p.Files, transpile.File{Name: routesStub, Src: d.stubSrc()})
		}
	}
	return pkgs, nil
}

// routesResult is what finishing the folder routes gives: the route table,
// its files, and the problems found.
type routesResult struct {
	routes []*folderRoute
	files  []load.Generated
	diags  []diag.Diagnostic
}

// err is the result's errors, nil when it has none.
func (r *routesResult) err() error {
	var l diag.List
	for _, d := range r.diags {
		if d.Severity == diag.Error {
			l = append(l, d)
		}
	}
	if len(l) == 0 {
		return nil
	}
	return l
}

// finish builds the route table from the transpiled module (gens, through
// overlay), and returns gens and the overlay with the stubs replaced by the
// generated files. With errors, the stubs are dropped and nothing added.
func (t *routeTree) finish(gens []load.Generated, overlay, tmp string) ([]load.Generated, string, *routesResult, error) {
	res := &routesResult{}
	if t == nil {
		return gens, overlay, res, nil
	}
	var drop []string
	for _, g := range gens {
		if filepath.Base(g.Target) == transpile.GoName(routesStub) {
			drop = append(drop, g.Target)
		}
	}
	gens = withoutStubs(gens)
	ov, err := readOverlay(overlay)
	if err != nil {
		return nil, "", nil, err
	}
	t.result = res
	t.check(ov, overlay, res)
	if res.err() == nil {
		res.files = t.generate(res.routes)
	}
	if len(drop) == 0 && len(res.files) == 0 {
		return gens, overlay, res, nil
	}
	if overlay == "" {
		overlay = filepath.Join(tmp, "overlay.json")
	}
	for _, target := range drop {
		delete(ov, target)
	}
	for i, g := range res.files {
		file := filepath.Join(tmp, fmt.Sprintf("routes%d_%s", i, filepath.Base(g.Target)))
		if err := os.WriteFile(file, g.Src, 0o644); err != nil {
			return nil, "", nil, err
		}
		ov[g.Target] = file
	}
	data, err := json.Marshal(struct{ Replace map[string]string }{ov})
	if err != nil {
		return nil, "", nil, err
	}
	if err := os.WriteFile(overlay, data, 0o644); err != nil {
		return nil, "", nil, err
	}
	return append(gens, res.files...), overlay, res, nil
}

// withoutStubs is gens without the stubs of the page packages.
func withoutStubs(gens []load.Generated) []load.Generated {
	return slices.DeleteFunc(gens, func(g load.Generated) bool { return filepath.Base(g.Target) == transpile.GoName(routesStub) })
}

// readOverlay is an overlay file's replacements; none for "".
func readOverlay(path string) (map[string]string, error) {
	ov := struct{ Replace map[string]string }{map[string]string{}}
	if path == "" {
		return ov.Replace, nil
	}
	data, err := os.ReadFile(path)
	if err != nil {
		return nil, err
	}
	if err := json.Unmarshal(data, &ov); err != nil {
		return nil, err
	}
	if ov.Replace == nil {
		ov.Replace = map[string]string{}
	}
	return ov.Replace, nil
}

// overlayContext is the build context seeing the files of an overlay as
// the go command does.
func overlayContext(ov map[string]string) *build.Context {
	ctx := build.Default
	ctx.ReadDir = func(dir string) ([]fs.FileInfo, error) {
		entries, err := os.ReadDir(dir)
		if err != nil {
			return nil, err
		}
		var infos []fs.FileInfo
		have := map[string]bool{}
		for _, e := range entries {
			p := filepath.Join(dir, e.Name())
			have[e.Name()] = true
			if r, ok := ov[p]; ok {
				if r == "" {
					continue
				}
				if fi, err := os.Stat(r); err == nil {
					infos = append(infos, overlaidInfo{fi, e.Name()})
				}
				continue
			}
			if fi, err := e.Info(); err == nil {
				infos = append(infos, fi)
			}
		}
		for target, r := range ov {
			if filepath.Dir(target) == dir && !have[filepath.Base(target)] && r != "" {
				if fi, err := os.Stat(r); err == nil {
					infos = append(infos, overlaidInfo{fi, filepath.Base(target)})
				}
			}
		}
		slices.SortFunc(infos, func(a, b fs.FileInfo) int { return strings.Compare(a.Name(), b.Name()) })
		return infos, nil
	}
	ctx.OpenFile = func(path string) (io.ReadCloser, error) {
		if r, ok := ov[path]; ok {
			if r == "" {
				return nil, os.ErrNotExist
			}
			path = r
		}
		return os.Open(path)
	}
	return &ctx
}

// overlaidInfo is an overlay file's info under the name it replaces.
type overlaidInfo struct {
	fs.FileInfo
	name string
}

func (i overlaidInfo) Name() string { return i.name }

// templateTypes declares the types of template-only pages, names, and
// their constructors.
func (d *routeDir) templateTypes(names []string) string {
	var b strings.Builder
	for _, name := range names {
		body := "struct{}"
		if d.params {
			body = "struct{ Params }"
		}
		file := d.templateFiles[slices.Index(d.templates, name)]
		fmt.Fprintf(&b, "\n// %s is the page %s renders.\ntype %s %s\n\n// New%s builds the page %s.\nfunc New%s() *%s { return &%s{} }\n",
			name, file, name, body, name, name, name, name, name)
	}
	return b.String()
}

// templatePage is the type a .vuka.html file's template renders, when the
// file has markup of its own (not only partials): about.vuka.html and
// terms-of-service.vuka.html render About and TermsOfService.
func templatePage(name string, src []byte) (string, bool) {
	inImports := false
	for _, line := range strings.Split(string(src), "\n") {
		l := strings.TrimSpace(line)
		switch {
		case l == "" || strings.HasPrefix(l, "//") || strings.HasPrefix(l, "package "):
			continue
		case inImports:
			inImports = l != ")"
			continue
		case strings.HasPrefix(l, "import"):
			inImports = strings.HasSuffix(l, "(")
			continue
		case strings.HasPrefix(l, "func ") || strings.HasPrefix(l, "<script") || strings.HasPrefix(l, "<style"):
			return "", false
		}
		break
	}
	var b strings.Builder
	for _, part := range strings.FieldsFunc(strings.TrimSuffix(name, ".vuka.html"), func(r rune) bool { return r == '-' || r == '_' || r == '.' }) {
		b.WriteString(upperFirst(part))
	}
	n := b.String()
	return n, token.IsIdentifier(n) && token.IsExported(n)
}

// topLevel records the names a Go or Vuka file declares at the top level:
// types in types, other names (functions, variables, constants) in others.
func topLevel(path string, src []byte, types map[string]bool, others map[string]diag.Span) {
	if strings.HasSuffix(path, ".go") {
		fset := token.NewFileSet()
		f, _ := parser.ParseFile(fset, path, src, parser.SkipObjectResolution)
		if f == nil {
			return
		}
		for _, decl := range f.Decls {
			switch d := decl.(type) {
			case *ast.FuncDecl:
				if d.Recv == nil {
					p := fset.Position(d.Name.Pos())
					others[d.Name.Name] = diag.Span{File: path, Line: p.Line, Col: p.Column}
				}
			case *ast.GenDecl:
				for _, spec := range d.Specs {
					switch sp := spec.(type) {
					case *ast.TypeSpec:
						types[sp.Name.Name] = true
					case *ast.ValueSpec:
						for _, id := range sp.Names {
							p := fset.Position(id.Pos())
							others[id.Name] = diag.Span{File: path, Line: p.Line, Col: p.Column}
						}
					}
				}
			}
		}
		return
	}
	for _, m := range typeDecl.FindAllSubmatch(src, -1) {
		types[string(m[1])] = true
	}
	for _, m := range topFunc.FindAllSubmatchIndex(src, -1) {
		others[string(src[m[2]:m[3]])] = diag.Span{File: path, Line: bytes.Count(src[:m[2]], []byte("\n")) + 1}
	}
}
