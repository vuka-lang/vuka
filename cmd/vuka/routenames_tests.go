// routeNamesTestGo is the file vuka test and vet add to each test package,
// through the overlay alone: its init registers the module's route names
// with web.RegisterRouteNames, so a test links by name without building
// the app.
const routeNamesTestGo = "vuka_routenames_gen_test.go"

// routeNameTests adds routeNamesTestGo to every package of the module with
// test files, as its external test package when it has one. Nothing is
// added when the module has no route names or the web it builds with
// can't register them.
func routeNameTests(root, modPath, tmp, overlay string, routes routeTrees, gens []load.Generated) (string, []load.Generated, error) {
	names := map[string]string{}
	for _, t := range routes {
		for n, nr := range t.named {
			if _, ok := names[n]; !ok {
				names[n] = nr.Path
			}
		}
	}
	if len(names) == 0 || modPath == webPath {
		return overlay, gens, nil
	}
	if mod, err := os.ReadFile(filepath.Join(root, "go.mod")); err != nil || !twRequire.Match(mod) {
		return overlay, gens, nil
	}
	ov, err := readOverlay(overlay)
	if err != nil {
		return overlay, gens, err
	}
	pkgs := testPackages(realPathOf(root), ov)
	if len(pkgs) == 0 || !webRegistersNames(root) {
		return overlay, gens, nil
	}
	var b strings.Builder
	for _, n := range slices.Sorted(maps.Keys(names)) {
		b.WriteString("\t\t" + strconv.Quote(n) + ": " + strconv.Quote(names[n]) + ",\n")
	}
	table := b.String()
	var add []load.Generated
	for _, dir := range slices.Sorted(maps.Keys(pkgs)) {
		target := filepath.Join(dir, routeNamesTestGo)
		if _, ok := ov[target]; ok || fileExists(target) {
			continue
		}
		src := "// Code generated by vuka test. DO NOT EDIT.\n\npackage " + pkgs[dir] + "\n\n" +
			"import vukaRouteNamesWeb \"" + webPath + "\"\n\n" +
			"func init() {\n\tvukaRouteNamesWeb.RegisterRouteNames(map[string]string{\n" + table + "\t})\n}\n"
		add = append(add, load.Generated{Target: target, Src: []byte(src)})
	}
	if len(add) == 0 {
		return overlay, gens, nil
	}
	if overlay, err = addToOverlay(overlay, tmp, add); err != nil {
		return overlay, gens, err
	}
	return overlay, append(gens, add...), nil
}

// testPackages are the module's directories, as the go command sees them,
// holding test files, each with the package a file added to its tests is
// in: the external test package's name when there is one, else the
// package's.
func testPackages(root string, ov map[string]string) map[string]string {
	out := map[string]string{}
	add := func(goDir string, src []byte) {
		f, err := parser.ParseFile(token.NewFileSet(), "", src, parser.PackageClauseOnly)
		if err != nil {
			return
		}
		name := f.Name.Name
		if cur, ok := out[goDir]; !ok || !strings.HasSuffix(cur, "_test") && strings.HasSuffix(name, "_test") {
			out[goDir] = name
		}
	}
	load.WalkDir(root, func(path string, e fs.DirEntry, err error) error {
		if err != nil {
			return nil
		}
		rel, _ := filepath.Rel(root, path)
		n := e.Name()
		if e.IsDir() {
			if path != root && (strings.HasPrefix(n, ".") || strings.HasPrefix(n, "_") && !load.InPages(filepath.ToSlash(rel)) ||
				n == "testdata" || n == "vendor" || n == "node_modules" || hasGoModFile(path) || load.IsGoName(path)) {
				return filepath.SkipDir
			}
			return nil
		}
		if !strings.HasSuffix(n, "_test.go") || strings.HasPrefix(n, ".") || strings.HasPrefix(n, "_") {
			return nil
		}
		if src, err := os.ReadFile(path); err == nil {
			add(load.GoDir(root, filepath.Dir(path)), src)
		}
		return nil
	})
	for target, file := range ov {
		if file == "" || !strings.HasSuffix(target, "_test.go") || !strings.HasPrefix(target, root+string(filepath.Separator)) {
			continue
		}
		if src, err := os.ReadFile(file); err == nil {
			add(filepath.Dir(target), src)
		}
	}
	return out
}

// webRegistersNames reports whether the web module the module at root
// builds with has RegisterRouteNames.
func webRegistersNames(root string) bool {
	c := exec.Command("go", "list", "-m", "-f", "{{.Dir}}", webPath)
	c.Dir = root
	out, err := c.Output()
	return err == nil && hasWebFunc(strings.TrimSpace(string(out)), "RegisterRouteNames")
}
