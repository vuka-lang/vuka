// keepModule is a module whose only import of example.com/greet is in a
// .vuka file, and which imports example.com/shared from both a .vuka and a
// .go file.
func keepModule(t *testing.T) string {
	t.Helper()
	dir := module(t, map[string]string{
		"main.vuka": `package main

import (
	"fmt"

	"example.com/greet"
	"example.com/shared"
)

func main() { fmt.Println(greet.Hello(), shared.X()) }
`,
		"helper.go": "package main\n\nimport _ \"example.com/shared\"\n",
	})
	localLib(t, dir, "greet", "package greet\n\nfunc Hello() string { return \"hi\" }\n")
	localLib(t, dir, "shared", "package shared\n\nfunc X() int { return 1 }\n")
	appendMod(t, dir, "\nrequire (\n\texample.com/greet v0.0.0\n\texample.com/shared v0.0.0\n)\n\n"+
		"replace example.com/greet => ../greet\n\nreplace example.com/shared => ../shared\n")
	tidyEnv(t, dir)
	return dir
}

func plainTidy(t *testing.T, dir string) {
	t.Helper()
	c := exec.Command("go", "mod", "tidy")
	c.Dir = dir
	if out, err := c.CombinedOutput(); err != nil {
		t.Fatalf("go mod tidy: %v\n%s", err, out)
	}
}

func readKeep(t *testing.T, dir string) string {
	t.Helper()
	src, err := os.ReadFile(filepath.Join(dir, "vukakeep", "vukakeep.go"))
	if err != nil {
		t.Fatal(err)
	}
	return string(src)
}

// TestModTidyKeepFile: vuka mod tidy writes a build-tagged file of the
// external packages only .vuka files import, and a plain go mod tidy then
// keeps them; without it, plain go mod tidy drops them.
func TestModTidyKeepFile(t *testing.T) {
	if testing.Short() {
		t.Skip("runs the go command")
	}
	dir := keepModule(t)

	var stdout, stderr bytes.Buffer
	if err := modTidy(nil, &stdout, &stderr); err != nil {
		t.Fatalf("%v\n%s", err, stderr.String())
	}
	if !strings.Contains(stdout.String(), "wrote   vukakeep/vukakeep.go") {
		t.Errorf("the output doesn't say the keep-file was written:\n%s", stdout.String())
	}
	keep := readKeep(t, dir)
	for _, want := range []string{"//go:build vukakeep\n", "generated by vuka", "do not edit", "package vukakeep\n", `_ "example.com/greet"`} {
		if !strings.Contains(keep, want) {
			t.Errorf("the keep-file lacks %q:\n%s", want, keep)
		}
	}
	if strings.Contains(keep, "example.com/shared") || strings.Contains(keep, `"fmt"`) || strings.Contains(keep, `"m/`) {
		t.Errorf("the keep-file holds imports it needn't:\n%s", keep)
	}

	plainTidy(t, dir)
	if got := readMod(t, dir); !requires(got, "example.com/greet") || !requires(got, "example.com/shared") {
		t.Errorf("a plain go mod tidy dropped a requirement:\n%s", got)
	}

	// Without the file, plain go mod tidy drops what only main.vuka imports.
	if err := os.RemoveAll(filepath.Join(dir, "vukakeep")); err != nil {
		t.Fatal(err)
	}
	plainTidy(t, dir)
	if requires(readMod(t, dir), "example.com/greet") {
		t.Error("a plain go mod tidy kept example.com/greet without the keep-file; the test shows nothing")
	}
}

// TestModTidyKeepFileIdempotent: a second vuka mod tidy leaves the file
// as it is, and the module's other files are untouched.
func TestModTidyKeepFileIdempotent(t *testing.T) {
	if testing.Short() {
		t.Skip("runs the go command")
	}
	dir := keepModule(t)
	var stdout, stderr bytes.Buffer
	if err := modTidy(nil, &stdout, &stderr); err != nil {
		t.Fatalf("%v\n%s", err, stderr.String())
	}
	path := filepath.Join(dir, "vukakeep", "vukakeep.go")
	old := time.Date(2001, 1, 1, 0, 0, 0, 0, time.UTC)
	if err := os.Chtimes(path, old, old); err != nil {
		t.Fatal(err)
	}
	stdout.Reset()
	if err := modTidy(nil, &stdout, &stderr); err != nil {
		t.Fatalf("%v\n%s", err, stderr.String())
	}
	if fi, _ := os.Stat(path); !fi.ModTime().Equal(old) {
		t.Error("the unchanged keep-file was written again")
	}
	if strings.Contains(stdout.String(), "vukakeep") {
		t.Errorf("the second run reports the keep-file:\n%s", stdout.String())
	}
	if err := modTidy([]string{"-check"}, &stdout, &stderr); err != nil {
		t.Errorf("-check of a tidy module: %v\n%s", err, stderr.String())
	}
}

// TestModTidyKeepFileCheck: -check fails on a missing or stale keep-file
// and writes nothing.
func TestModTidyKeepFileCheck(t *testing.T) {
	if testing.Short() {
		t.Skip("runs the go command")
	}
	dir := keepModule(t)
	var stdout, stderr bytes.Buffer
	if err := modTidy(nil, &stdout, &stderr); err != nil {
		t.Fatalf("%v\n%s", err, stderr.String())
	}
	path := filepath.Join(dir, "vukakeep", "vukakeep.go")
	good := readKeep(t, dir)

	check := func(want string) {
		t.Helper()
		stderr.Reset()
		err := modTidy([]string{"-check"}, &stdout, &stderr)
		if st, ok := err.(exitStatus); !ok || st != 1 {
			t.Fatalf("-check: %v, want exit status 1\n%s", err, stderr.String())
		}
		if !strings.Contains(stderr.String(), want) {
			t.Errorf("-check says:\n%s\nwant %q", stderr.String(), want)
		}
	}

	if err := os.Remove(path); err != nil {
		t.Fatal(err)
	}
	check("vukakeep/vukakeep.go is missing")
	if fileExists(path) {
		t.Error("-check wrote the keep-file")
	}

	stale := strings.Replace(good, `_ "example.com/greet"`, `_ "example.com/gone"`, 1)
	writeFile(t, path, stale)
	check("is out of date")
	if got := readKeep(t, dir); got != stale {
		t.Error("-check changed the keep-file")
	}
}

// TestModTidyNoKeepFile: no external package only .vuka files import, no
// file; one nothing calls for is removed; one that isn't vuka's is left.
func TestModTidyNoKeepFile(t *testing.T) {
	if testing.Short() {
		t.Skip("runs the go command")
	}
	dir := module(t, map[string]string{
		"main.vuka": "package main\n\nimport \"fmt\"\n\nfunc main() { fmt.Println(1) }\n",
	})
	// No requirement of the runtime, which a module requiring it always keeps.
	writeFile(t, filepath.Join(dir, "go.mod"), "module m\n\ngo 1.24\n")
	os.Remove(filepath.Join(dir, "go.sum"))
	tidyEnv(t, dir)
	var stdout, stderr bytes.Buffer
	if err := modTidy(nil, &stdout, &stderr); err != nil {
		t.Fatalf("%v\n%s", err, stderr.String())
	}
	if fileExists(filepath.Join(dir, keepDir)) {
		t.Errorf("a keep-file was written for a module with no such import: %v", treeFiles(t, dir))
	}

	// A keep-file nothing calls for any more is flagged, then removed.
	path := filepath.Join(dir, keepDir, keepName)
	stale := "//go:build vukakeep\n\n// generated by vuka\n\npackage vukakeep\n\nimport _ \"example.com/gone\"\n"
	writeFile(t, path, stale)
	stderr.Reset()
	if err := modTidy([]string{"-check"}, &stdout, &stderr); err == nil || !strings.Contains(stderr.String(), "is no longer needed") {
		t.Errorf("-check of an unwanted keep-file: %v\n%s", err, stderr.String())
	}
	stdout.Reset()
	if err := modTidy(nil, &stdout, &stderr); err != nil {
		t.Fatalf("%v\n%s", err, stderr.String())
	}
	if fileExists(path) || fileExists(filepath.Dir(path)) {
		t.Error("vuka mod tidy left a keep-file nothing calls for")
	}
	if !strings.Contains(stdout.String(), "removed vukakeep/vukakeep.go") {
		t.Errorf("the output doesn't say the keep-file was removed:\n%s", stdout.String())
	}

	// A file at that path that isn't vuka's is the module's own.
	mine := "package vukakeep\n"
	writeFile(t, path, mine)
	if err := modTidy(nil, &stdout, &stderr); err == nil || !strings.Contains(err.Error(), "vuka didn't write it") {
		t.Errorf("a file of the module's own at the keep-file's path: %v", err)
	}
	if got := readKeep(t, dir); got != mine {
		t.Error("the module's own file was changed")
	}
}

func TestKeepable(t *testing.T) {
	for path, want := range map[string]bool{
		"fmt": false, "net/http": false, "C": false,
		"example.com/m": false, "example.com/m/x": false,
		"example.com/mx": true, "github.com/a/b": true, "golang.org/x/crypto/bcrypt": true,
	} {
		if got := keepable(path, "example.com/m"); got != want {
			t.Errorf("keepable(%q) = %v, want %v", path, got, want)
		}
	}
}

// TestBuildWritesKeepFile: vuka build refreshes the keep-file, and the
// build tag keeps it out of the binary and the build.
func TestBuildWritesKeepFile(t *testing.T) {
	if testing.Short() {
		t.Skip("runs the go command")
	}
	dir := keepModule(t)
	var out bytes.Buffer
	if err := runGo("build", []string{"-o", filepath.Join(t.TempDir(), "app"), "./..."}, io.Discard, &out); err != nil {
		t.Fatalf("vuka build: %v\n%s", err, out.String())
	}
	if keep := readKeep(t, dir); !strings.Contains(keep, `_ "example.com/greet"`) {
		t.Errorf("vuka build's keep-file:\n%s", keep)
	}
}
