package main

// A model's typed fields are the orm's generated Go: User.Email in a .vuka
// file is UserColumns.Email, a field of UserFields in user_gen.go, which the
// editor never has. gopls answers on that Go; the proxy takes each of its
// locations there back to what the declaration stands for — the model, or
// the field of the struct declaring it — which the generator names in an
// //orm:source directive (by the generator's naming, for an orm writing
// none). So definition lands on the model's field, hover shows it, and
// references join the field's uses with its typed field's.

import (
	"bytes"
	"encoding/json"
	"go/ast"
	"go/parser"
	"go/token"
	"os"
	"path/filepath"
	"regexp"
	"strings"
)

// ormgenOutput starts every file the orm's generator writes.
var ormgenOutput = []byte("// Code generated by ormgen. DO NOT EDIT.")

// ormSource is what a generated declaration stands for: the type typ (of
// the package at pkg, "" for the generated file's own), or its field.
type ormSource struct{ typ, field, pkg string }

// sourceDirective reads the //orm:source directive of a doc comment.
func sourceDirective(doc *ast.CommentGroup) (ormSource, bool) {
	if doc == nil {
		return ormSource{}, false
	}
	for _, c := range doc.List {
		rest, ok := strings.CutPrefix(c.Text, "//orm:source ")
		if !ok {
			continue
		}
		f := strings.Fields(rest)
		if len(f) == 0 {
			continue
		}
		var s ormSource
		s.typ, s.field, _ = strings.Cut(f[0], ".")
		if len(f) > 1 {
			s.pkg = f[1]
		}
		return s, s.typ != ""
	}
	return ormSource{}, false
}

// typedFieldsSuffixes end the names the generator gives a model's typed
// fields' declarations: UserColumns, UserFields, UserFieldsAt, ...
var typedFieldsSuffixes = []string{"FieldsAt", "FieldsIn", "PathAt", "Fields", "Columns", "Path"}

// modelNamed is the model a typed-fields declaration's name is named after.
func modelNamed(name string) (string, bool) {
	for _, suf := range typedFieldsSuffixes {
		if m, ok := strings.CutSuffix(name, suf); ok && m != "" {
			return m, true
		}
	}
	return "", false
}

// ormSourceAt is what the declaration whose name the ormgen output src
// has at off stands for. Elsewhere — a use, in a constructor's body — it is
// nothing: the generated Go's own uses are no model's.
func ormSourceAt(src []byte, off int) (ormSource, bool) {
	if !bytes.HasPrefix(src, ormgenOutput) {
		return ormSource{}, false
	}
	fset := token.NewFileSet()
	f, _ := parser.ParseFile(fset, "", src, parser.ParseComments|parser.SkipObjectResolution)
	if f == nil {
		return ormSource{}, false
	}
	tf := fset.File(f.Pos())
	in := func(n ast.Node) bool { return tf.Offset(n.Pos()) <= off && off <= tf.Offset(n.End()) }
	named := func(doc *ast.CommentGroup, name, field string) (ormSource, bool) {
		if s, ok := sourceDirective(doc); ok {
			return s, true
		}
		m, ok := modelNamed(name)
		return ormSource{typ: m, field: field}, ok
	}
	for _, d := range f.Decls {
		if !in(d) {
			continue
		}
		switch d := d.(type) {
		case *ast.FuncDecl:
			if !in(d.Name) {
				return ormSource{}, false
			}
			if d.Recv != nil && len(d.Recv.List) == 1 {
				if id, ok := d.Recv.List[0].Type.(*ast.Ident); ok {
					return named(d.Doc, id.Name, d.Name.Name)
				}
			}
			return named(d.Doc, d.Name.Name, "")
		case *ast.GenDecl:
			for _, spec := range d.Specs {
				if !in(spec) {
					continue
				}
				doc := d.Doc
				switch s := spec.(type) {
				case *ast.TypeSpec:
					if st, ok := s.Type.(*ast.StructType); ok {
						for _, fld := range st.Fields.List {
							if len(fld.Names) > 0 && in(fld.Names[0]) {
								return named(fld.Doc, s.Name.Name, fld.Names[0].Name)
							}
						}
					}
					if !in(s.Name) {
						return ormSource{}, false
					}
					if s.Doc != nil {
						doc = s.Doc
					}
					return named(doc, s.Name.Name, "")
				case *ast.ValueSpec:
					if !in(s.Names[0]) {
						return ormSource{}, false
					}
					if s.Doc != nil {
						doc = s.Doc
					}
					return named(doc, s.Names[0].Name, "")
				}
			}
		}
	}
	return ormSource{}, false
}

// ormSourceDecl is where s, read in the generated Go of the package at dir,
// is declared: the type's name, or the field's in the struct declaring it
// (looked for in the structs it embeds when s names the model, as an orm
// writing no directives does). A field not found is its type's.
func (p *proxy) ormSourceDecl(dir string, s ormSource) (string, lspRange, bool) {
	if s.pkg != "" {
		if dir = p.importDir(s.pkg); dir == "" {
			return "", lspRange{}, false
		}
	}
	files := declaring(p.packageFiles(dir))
	ts, f := findTypeSpec(files, s.typ)
	if ts == nil {
		return "", lspRange{}, false
	}
	if s.field != "" {
		if f2, id := p.fieldIn(dir, f, ts, s.field, 0); id != nil {
			f = f2
			return pathToURI(f.path), identRange(f, id), true
		}
	}
	return pathToURI(f.path), identRange(f, ts.Name), true
}

// fieldIn finds the field name of the struct ts declares (in f, of the
// package at dir), or of a struct it embeds.
func (p *proxy) fieldIn(dir string, f *staticsFile, ts *ast.TypeSpec, name string, depth int) (*staticsFile, *ast.Ident) {
	st, ok := ts.Type.(*ast.StructType)
	if !ok || depth > 4 {
		return nil, nil
	}
	for _, fld := range st.Fields.List {
		for _, id := range fld.Names {
			if id.Name == name {
				return f, id
			}
		}
	}
	for _, fld := range st.Fields.List {
		if len(fld.Names) > 0 {
			continue
		}
		d2, n2, ok := p.namedTarget(dir, f, fld.Type)
		if !ok {
			continue
		}
		if ts2, f2 := findTypeSpec(declaring(p.packageFiles(d2)), n2); ts2 != nil {
			if f3, id := p.fieldIn(d2, f2, ts2, name, depth+1); id != nil {
				return f3, id
			}
		}
	}
	return nil, nil
}

func identRange(f *staticsFile, id *ast.Ident) lspRange {
	tf := f.fset.File(id.Pos())
	start := tf.Offset(id.Pos())
	return lspRange{positionOf(f.src, start), positionOf(f.src, start+len(id.Name))}
}

// locationKeys are a Location's or a LocationLink's uri and ranges.
var locationKeys = []struct{ uri, rng string }{{"uri", "range"}, {"targetUri", "targetSelectionRange"}}

// withModelSources is gopls's answer v with each location in the orm's
// generated Go moved to the declaration it stands for.
func (p *proxy) withModelSources(v any) any {
	list, single := v.([]any), false
	if m, ok := v.(map[string]any); ok {
		list, single = []any{m}, true
	}
	moved := false
	for _, e := range list {
		loc, _ := e.(map[string]any)
		for _, k := range locationKeys {
			uri, _ := loc[k.uri].(string)
			r, ok := toRange(loc[k.rng])
			if uri == "" || !ok {
				continue
			}
			to, tr, ok := p.modelSourceOf(uri, r.Start)
			if !ok {
				continue
			}
			loc[k.uri], loc[k.rng], moved = to, tr, true
			if k.uri == "targetUri" {
				loc["targetRange"] = tr
			}
		}
	}
	if !moved {
		return v
	}
	if single {
		return list[0]
	}
	return withLocations(nil, list...)
}

// modelSourceOf is where what the orm's generated Go at uri declares at pos
// stands for is declared.
func (p *proxy) modelSourceOf(uri string, pos lspPosition) (string, lspRange, bool) {
	if !strings.HasSuffix(uri, "_gen.go") && !strings.HasSuffix(uri, "_gen_test.go") {
		return "", lspRange{}, false // never the orm's
	}
	src := p.goFile(uri)
	s, ok := ormSourceAt(src, offsetOf(src, pos))
	if !ok {
		return "", lspRange{}, false
	}
	return p.ormSourceDecl(filepath.Dir(uriToPath(uri)), s)
}

// genAt is a request's document and position in the generated Go, for
// asking gopls again.
func genAt(params map[string]any) map[string]any {
	return map[string]any{"textDocument": params["textDocument"], "position": params["position"]}
}

// definitionIn is gopls's definition at a request's generated position, as
// gopls gives it: in generated Go.
func (p *proxy) definitionIn(at map[string]any) (string, lspRange, bool) {
	res, ok := p.ask("textDocument/definition", at)
	if !ok {
		return "", lspRange{}, false
	}
	var v any
	_ = json.Unmarshal(res, &v)
	if list, ok := v.([]any); ok && len(list) > 0 {
		v = list[0]
	}
	return location(v)
}

// typedFieldsHover reports whether gopls's hover is on a typed field: its
// text names a model's typed fields.
func typedFieldsHover(raw json.RawMessage) bool {
	return bytes.Contains(raw, []byte("Fields"))
}

// modelHover is the hover on a typed field (usual, gopls's): the model
// field's own — its declaration and doc — then the typed field's type.
func (p *proxy) modelHover(at map[string]any, usual any) any {
	uri, r, ok := p.definitionIn(at)
	if !ok {
		return usual
	}
	to, tr, ok := p.modelSourceOf(uri, r.Start)
	if !ok {
		return usual
	}
	res, ok := p.ask("textDocument/hover", map[string]any{"textDocument": map[string]any{"uri": to}, "position": tr.Start})
	if !ok {
		return usual
	}
	var model map[string]any
	if json.Unmarshal(res, &model) != nil || model == nil {
		return usual
	}
	mine, _ := hoverValue(model)
	h, _ := usual.(map[string]any)
	typed, ok := hoverValue(h)
	if mine == "" || !ok {
		return usual
	}
	p.mu.Lock()
	names := p.virtual[uriToPath(to)].namesOf()
	p.mu.Unlock()
	mine = layoutNote.ReplaceAllString(demangle(mine, names), "")
	if block := firstCodeBlock(typed); block != "" {
		mine += "\n\n---\n\n" + block
	}
	h["contents"] = map[string]any{"kind": "markdown", "value": mine}
	return h
}

// layoutNote is the size and offset gopls notes in a hover on a declaration.
var layoutNote = regexp.MustCompile(` ?// size=\d+ \(0x[0-9a-f]+\)(, [a-z]+=\d+ \(0x[0-9a-f]+\))*`)

func hoverValue(h map[string]any) (string, bool) {
	c, _ := h["contents"].(map[string]any)
	s, ok := c["value"].(string)
	return s, ok
}

// firstCodeBlock is the first fenced block of markdown s.
func firstCodeBlock(s string) string {
	start := strings.Index(s, "```")
	if start < 0 {
		return ""
	}
	end := strings.Index(s[start+3:], "```")
	if end < 0 {
		return ""
	}
	return s[start : start+3+end+3]
}

// modelRefs is what references at a request's generated position (at)
// misses of a model's field: asked on the field, its typed fields' uses;
// asked on a typed field, the field's own. Each location is in the source.
func (p *proxy) modelRefs(at map[string]any, ctx any, origin *vfile) []any {
	uri, r, ok := p.definitionIn(at)
	if !ok {
		return nil
	}
	dir, src := filepath.Dir(uriToPath(uri)), p.goFile(uri)
	var key ormSource // the field, by its type's package directory
	var asks []map[string]any
	if s, ok := ormSourceAt(src, offsetOf(src, r.Start)); ok {
		if s.field == "" {
			return nil
		}
		to, tr, ok := p.ormSourceDecl(dir, s)
		if !ok {
			return nil
		}
		asks = append(asks, map[string]any{"uri": to, "position": tr.Start})
		key = ormSource{typ: s.typ, field: s.field, pkg: p.sourceDir(dir, s.pkg)}
	} else {
		typ, field, ok := fieldAt(src, offsetOf(src, r.Start))
		if !ok {
			return nil
		}
		key = ormSource{typ: typ, field: field, pkg: dir}
	}
	for _, d := range p.typedDecls(key) {
		if d["uri"] != uri || d["position"] != r.Start {
			asks = append(asks, d)
		}
	}
	var out []any
	for _, a := range asks {
		res, ok := p.ask("textDocument/references", map[string]any{"textDocument": map[string]any{"uri": a["uri"]},
			"position": a["position"], "context": ctx})
		if !ok {
			continue
		}
		var v any
		_ = json.Unmarshal(res, &v)
		if list, ok := p.rewrite(p.withModelSources(v), nil, origin).([]any); ok {
			out = append(out, list...)
		}
	}
	return out
}

// sourceDir is the directory of the package an ormSource names, read in
// the generated Go of the package at dir.
func (p *proxy) sourceDir(dir, pkg string) string {
	if pkg == "" {
		return dir
	}
	return p.importDir(pkg)
}

// fieldAt is the struct type and field whose name src declares at off.
func fieldAt(src []byte, off int) (string, string, bool) {
	fset := token.NewFileSet()
	f, _ := parser.ParseFile(fset, "", src, parser.SkipObjectResolution)
	if f == nil {
		return "", "", false
	}
	tf := fset.File(f.Pos())
	for _, d := range f.Decls {
		g, ok := d.(*ast.GenDecl)
		if !ok || g.Tok != token.TYPE {
			continue
		}
		for _, spec := range g.Specs {
			ts := spec.(*ast.TypeSpec)
			st, ok := ts.Type.(*ast.StructType)
			if !ok {
				continue
			}
			for _, fld := range st.Fields.List {
				for _, id := range fld.Names {
					if s := tf.Offset(id.Pos()); s <= off && off <= s+len(id.Name) {
						return ts.Name.Name, id.Name, true
					}
				}
			}
		}
	}
	return "", "", false
}

// typedDecls are the typed fields standing for key's field (key.pkg its
// type's package directory): in the proxy's generated typed fields, and
// those written in the field's package.
func (p *proxy) typedDecls(key ormSource) []map[string]any {
	p.mu.Lock()
	files := map[string][]byte{}
	for path, vf := range p.virtual {
		if vf.source == "" && bytes.HasPrefix(vf.gen, ormgenOutput) {
			files[path] = vf.gen
		}
	}
	p.mu.Unlock()
	entries, _ := os.ReadDir(key.pkg)
	for _, e := range entries {
		path := filepath.Join(key.pkg, e.Name())
		if _, ok := files[path]; ok || !strings.HasSuffix(e.Name(), "_gen.go") {
			continue
		}
		if src, err := os.ReadFile(path); err == nil && bytes.HasPrefix(src, ormgenOutput) {
			files[path] = src
		}
	}
	directive := []byte("//orm:source " + key.typ + "." + key.field)
	var out []map[string]any
	for path, src := range files {
		dir := filepath.Dir(path)
		if !bytes.Contains(src, directive) && (dir != key.pkg || !bytes.Contains(src, []byte(key.typ+"Fields"))) {
			continue
		}
		fset := token.NewFileSet()
		f, _ := parser.ParseFile(fset, path, src, parser.ParseComments|parser.SkipObjectResolution)
		if f == nil {
			continue
		}
		sf := &staticsFile{path: path, ast: f, fset: fset, src: src}
		ast.Inspect(f, func(n ast.Node) bool {
			var id *ast.Ident
			switch n := n.(type) {
			case *ast.Field:
				if len(n.Names) > 0 {
					id = n.Names[0]
				}
			case *ast.FuncDecl:
				id = n.Name
			}
			if id == nil || id.Name != key.field {
				return true
			}
			s, ok := ormSourceAt(src, fset.File(id.Pos()).Offset(id.Pos()))
			if ok && s.typ == key.typ && s.field == key.field && p.sourceDir(dir, s.pkg) == key.pkg {
				out = append(out, map[string]any{"uri": pathToURI(path), "position": identRange(sf, id).Start})
			}
			return true
		})
	}
	return out
}

// sameWord is gp, where src's offset off maps in gen, moved onto the word
// off is in when gp lands on another one: a source span lowered to longer
// Go maps as a whole, so Post.Objects, orm.Objects[Post]() in the Go, maps
// each of its offsets to the Go's start. It looks on gp's line, after gp.
func sameWord(src []byte, off int, gen []byte, gp lspPosition) lspPosition {
	start, end := wordAt(src, off)
	word := src[start:end]
	g := offsetOf(gen, gp)
	if len(word) == 0 || g > len(gen) {
		return gp
	}
	if gs, ge := wordAt(gen, g); bytes.Equal(gen[gs:ge], word) {
		return gp
	}
	line := gen[g:]
	if nl := bytes.IndexByte(line, '\n'); nl >= 0 {
		line = line[:nl]
	}
	for i := 0; ; {
		k := bytes.Index(line[i:], word)
		if k < 0 {
			return gp
		}
		k += i
		at := g + k
		if (at == 0 || !isIdentByte(gen[at-1])) && (at+len(word) == len(gen) || !isIdentByte(gen[at+len(word)])) {
			return positionOf(gen, at+off-start)
		}
		i = k + 1
	}
}

// wordAt is the identifier around off in src.
func wordAt(src []byte, off int) (int, int) {
	start, end := min(off, len(src)), min(off, len(src))
	for start > 0 && isIdentByte(src[start-1]) {
		start--
	}
	for end < len(src) && isIdentByte(src[end]) {
		end++
	}
	return start, end
}
