// A watch build keeps the fixed HTML of the module's templates out of the
// packages that render them. Go compiles a package again whenever the
// archive of a package it imports changes, whatever changed in it, so a
// text edit in a shared component compiled every package importing it.
// Instead each ui.HTML("…", …) of the module's generated Go reads its text
// by name, devstatic.S("key"), and one package of the watch's own,
// devStaticsDir, holds every text and registers it as it initializes: a text
// edit then changes that package's archive and the main package's, which
// imports it, and no other. Lines and columns are kept, so errors and
// panics point where they did. vuka build compiles the templates as they
// are.

const (
	devStaticPath = transpileRuntime + "/devstatic"
	// devStaticsDir is the package holding the texts, in the module's root
	// on no disk. Its name sorts before any other package of the module (but
	// the root's) so it initializes first: packages initialize in import
	// path order as soon as their imports have. The root's own package, if
	// not main, keeps its texts.
	devStaticsDir = "0vukastatics"
	devStaticName = "vukadevstatic_"
	uiImportPath  = "github.com/vuka-lang/ui/v2"
)

const transpileRuntime = "github.com/vuka-lang/vuka/v2"

// devStaticsMain is the directory of the main package a watch builds from dir
// (pkg, vuka run's), when its templates' fixed HTML can be kept out of
// their packages: pkg names a directory of the module at root, and the
// module's vuka runtime has the devstatic package. "" otherwise
// (VUKA_DEV_STATICS=off, too).
func devStaticsMain(root, dir string, pkg, env []string) string {
	if strings.EqualFold(os.Getenv("VUKA_DEV_STATICS"), "off") || len(pkg) > 1 {
		return ""
	}
	main := dir
	if len(pkg) == 1 {
		if strings.HasSuffix(pkg[0], ".go") || strings.HasSuffix(pkg[0], ".vuka") || !strings.HasPrefix(pkg[0], ".") {
			return "" // files, or an import path
		}
		main = filepath.Join(dir, pkg[0])
	}
	if rel, err := filepath.Rel(root, main); err != nil || strings.HasPrefix(rel, "..") {
		return ""
	}
	c := exec.Command("go", "list", "-e", "-f", "{{.Dir}}", devStaticPath)
	c.Dir, c.Env = dir, env
	if out, err := c.Output(); err != nil || len(bytes.TrimSpace(out)) == 0 {
		return "" // a vuka runtime from before it
	}
	return main
}

// devStatics rewrites, through overlay, the generated Go of gens so that the
// fixed HTML its templates pass ui.HTML is read from the package
// devStaticsDir, which it adds, linked by the main package in mainDir. It
// returns the new overlay.
func devStatics(root, modPath, tmp, overlay, mainDir string, gens []load.Generated) (string, error) {
	ov, err := readOverlay(overlay)
	if err != nil {
		return overlay, err
	}
	var pairs []string
	ids := map[string]string{} // file ID → its target
	n := 0
	for _, g := range gens {
		dir := filepath.Dir(g.Target)
		if !strings.HasSuffix(g.Target, ".go") || strings.HasSuffix(g.Target, "_test.go") || dir == root && dir != mainDir ||
			ov[g.Target] == "" || !bytes.Contains(g.Src, []byte("HTML(")) {
			continue
		}
		rel, err := filepath.Rel(root, g.Target)
		if err != nil || strings.HasPrefix(rel, "..") {
			continue
		}
		id := staticsFileID(filepath.ToSlash(rel))
		if other, ok := ids[id]; ok && other != g.Target {
			continue // two files' IDs collide: this one keeps its texts
		}
		src, texts, ok := devStaticSrc(g.Src, id)
		if !ok {
			continue
		}
		ids[id] = g.Target
		file := filepath.Join(tmp, fmt.Sprintf("ds%d_%s", n, filepath.Base(g.Target)))
		n++
		if err := os.WriteFile(file, src, 0o644); err != nil {
			return overlay, err
		}
		ov[g.Target] = file
		pairs = append(pairs, texts...)
	}
	if len(pairs) == 0 {
		return overlay, nil
	}
	var b bytes.Buffer
	b.WriteString("// Code generated by vuka run -watch: the fixed HTML of the module's templates. DO NOT EDIT.\n\npackage vukastatics\n\nimport \"" + devStaticPath + "\"\n\nfunc init() { devstatic.Set(statics[:]) }\n\nvar statics = [...]string{\n")
	for _, s := range pairs {
		b.WriteString("\t" + strconv.Quote(s) + ",\n")
	}
	b.WriteString("}\n")
	file := filepath.Join(tmp, "ds_statics.go")
	if err := os.WriteFile(file, b.Bytes(), 0o644); err != nil {
		return overlay, err
	}
	ov[filepath.Join(root, devStaticsDir, "statics.go")] = file
	link := filepath.Join(tmp, "ds_link.go")
	if err := os.WriteFile(link, []byte("package main\n\nimport _ \""+modPath+"/"+devStaticsDir+"\"\n"), 0o644); err != nil {
		return overlay, err
	}
	ov[filepath.Join(mainDir, "zz_vukastatics.go")] = link
	data, err := json.Marshal(struct{ Replace map[string]string }{ov})
	if err != nil {
		return overlay, err
	}
	if overlay == "" {
		overlay = filepath.Join(tmp, "overlay.json")
	}
	return overlay, os.WriteFile(overlay, data, 0o644)
}

// staticsFileID names a generated file in its texts' keys: short, as a key must
// fit where its text was.
func staticsFileID(rel string) string {
	h := fnv.New32a()
	h.Write([]byte(rel))
	return strconv.FormatUint(uint64(h.Sum32()), 36)
}

// devStaticSrc is src with the fixed HTML of each ui.HTML call read through
// devstatic, and the texts, key and text in turn; ok is false when it has
// none it can move. A literal is replaced by a call of the same lines and
// the same end column; one too short to hold its call stays.
func devStaticSrc(src []byte, id string) (out []byte, texts []string, ok bool) {
	fset := token.NewFileSet()
	f, err := parser.ParseFile(fset, "", src, 0)
	if err != nil {
		return nil, nil, false
	}
	uiName := ""
	var importAt int // where the import of devstatic goes: after `import (` or before `import "x"`
	for _, d := range f.Decls {
		g, ok := d.(*ast.GenDecl)
		if !ok || g.Tok != token.IMPORT {
			continue
		}
		if importAt == 0 {
			if g.Lparen.IsValid() {
				importAt = fset.Position(g.Lparen).Offset + 1
			} else {
				importAt = -fset.Position(g.Specs[0].Pos()).Offset - 1
			}
		}
		for _, s := range g.Specs {
			s := s.(*ast.ImportSpec)
			if path, _ := strconv.Unquote(s.Path.Value); path == uiImportPath {
				uiName = "ui"
				if s.Name != nil {
					uiName = s.Name.Name
				}
			}
			if s.Name != nil && s.Name.Name == devStaticName {
				return nil, nil, false
			}
		}
	}
	if uiName == "" || uiName == "_" || uiName == "." || importAt == 0 {
		return nil, nil, false
	}
	type edit struct {
		from, to int
		text     string
	}
	var edits []edit
	ast.Inspect(f, func(n ast.Node) bool {
		call, ok := n.(*ast.CallExpr)
		if !ok || len(call.Args) == 0 {
			return true
		}
		sel, ok := call.Fun.(*ast.SelectorExpr)
		if !ok || sel.Sel.Name != "HTML" {
			return true
		}
		if x, ok := sel.X.(*ast.Ident); !ok || x.Name != uiName || x.Obj != nil {
			return true // not the package: a local of its name
		}
		lit, ok := call.Args[0].(*ast.BasicLit)
		if !ok || lit.Kind != token.STRING {
			return true
		}
		text, err := strconv.Unquote(lit.Value)
		if err != nil {
			return true
		}
		key := id + "." + strconv.Itoa(len(texts)/2)
		repl, fits := sameShape(lit.Value, devStaticName+".S("+strconv.Quote(key))
		if !fits {
			return true
		}
		from := fset.Position(lit.Pos()).Offset
		edits = append(edits, edit{from, from + len(lit.Value), repl})
		texts = append(texts, key, text)
		return true
	})
	if len(edits) == 0 {
		return nil, nil, false
	}
	var b bytes.Buffer
	at := 0
	imp := devStaticName + " \"" + devStaticPath + "\";"
	if importAt > 0 {
		b.Write(src[:importAt])
		b.WriteString(imp)
		at = importAt
	} else {
		// import "x": import (vukadevstatic_ "…"; "x") on the same line
		start := -importAt - 1
		b.Write(src[:start])
		b.WriteString("(" + imp)
		end := start + len(f.Imports[0].Path.Value)
		if f.Imports[0].Name != nil {
			end = start + int(f.Imports[0].Path.End()-f.Imports[0].Name.Pos())
		}
		b.Write(src[start:end])
		b.WriteString(")")
		at = end
	}
	slices.SortFunc(edits, func(a, b edit) int { return a.from - b.from })
	for _, e := range edits {
		if e.from < at {
			return nil, nil, false
		}
		b.Write(src[at:e.from])
		b.WriteString(e.text)
		at = e.to
	}
	b.Write(src[at:])
	return b.Bytes(), texts, true
}

// sameShape is call, the start of a call missing its closing parenthesis,
// laid out as lit is: as many lines, its last as long, the call's argument
// list holding the newlines in a comment. fits is false when lit's single
// line is shorter than call.
func sameShape(lit, call string) (string, bool) {
	lines := strings.Count(lit, "\n")
	if lines == 0 {
		if len(call)+1 > len(lit) {
			return "", false
		}
		return call + strings.Repeat(" ", len(lit)-len(call)-1) + ")", true
	}
	last := len(lit) - strings.LastIndexByte(lit, '\n') - 1
	// call,/*
	// …
	// */
	//    )   the ) where lit's closing quote was
	return call + ",/*" + strings.Repeat("\n", lines-1) + "*/\n" + strings.Repeat(" ", last-1) + ")", true
}
