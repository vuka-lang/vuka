const staticsGo = "// Code generated by vuka from card.vuka.html. DO NOT EDIT.\n\n//line card.vuka.html:2\npackage parts\n\nimport (\n\t\"github.com/vuka-lang/ui/v2\"\n)\n\nfunc (c Card) View() ui.Node {\n\tvar items ui.Node\n\titems = ui.HTML(`{x}`, c.X)\n\treturn ui.HTML(`\n<div class=\"card\">\n  <h2>Hello</h2>{items}\n</div>`, items)\n}\n\nfunc (c Card) Label() ui.Node { return ui.HTML(\"<b>a long enough label</b>{c}\", c.Name) }\n\nfunc other(ui fake) { ui.HTML(\"<p>not the package's</p>\") }\n"

// TestDevStaticSrc: each ui.HTML literal long enough is read through
// devstatic, the texts come out in order, and every other token keeps its
// line and column.
func TestDevStaticSrc(t *testing.T) {
	out, texts, ok := devStaticSrc([]byte(staticsGo), "f1")
	if !ok {
		t.Fatal("nothing moved")
	}
	if _, err := parser.ParseFile(token.NewFileSet(), "", out, 0); err != nil {
		t.Fatalf("the rewritten Go doesn't parse: %v\n%s", err, out)
	}
	want := []string{"f1.0", "\n<div class=\"card\">\n  <h2>Hello</h2>{items}\n</div>", "f1.1", "<b>a long enough label</b>{c}"}
	if strings.Join(texts, "|") != strings.Join(want, "|") {
		t.Errorf("texts: %q, want %q", texts, want)
	}
	for _, s := range []string{"`{x}`", "\"<p>not the package's</p>\"", `vukadevstatic_.S("f1.0",`, `vukadevstatic_.S("f1.1"`} {
		if !strings.Contains(string(out), s) {
			t.Errorf("no %s in\n%s", s, out)
		}
	}
	// Every token but the literals and the import keeps its place.
	type tok struct {
		line, col int
		lit       string
	}
	toks := func(src []byte) (out []tok) {
		fset := token.NewFileSet()
		f := fset.AddFile("", -1, len(src))
		var sc scanner.Scanner
		sc.Init(f, src, nil, 0)
		for {
			pos, t, lit := sc.Scan()
			if t == token.EOF {
				return out
			}
			if t == token.STRING || t == token.IMPORT || t == token.LPAREN && len(out) > 0 && out[len(out)-1].lit == "import" {
				continue
			}
			p := fset.Position(pos)
			if lit == "" {
				lit = t.String()
			}
			out = append(out, tok{p.Line, p.Column, lit})
		}
	}
	var after []tok
	for _, x := range toks(out) {
		if x.lit != "vukadevstatic_" && x.lit != "." && x.lit != "S" && x.lit != "," && x.lit != ";" && x.lit != ")" && x.lit != "(" {
			after = append(after, x)
		}
	}
	var before []tok
	for _, x := range toks([]byte(staticsGo)) {
		if x.lit != "." && x.lit != "," && x.lit != ";" && x.lit != ")" && x.lit != "(" {
			before = append(before, x)
		}
	}
	if len(before) != len(after) {
		t.Fatalf("%d tokens, then %d:\n%s", len(before), len(after), out)
	}
	for i := range before {
		if before[i] != after[i] {
			t.Errorf("token %q moved from %d:%d to %d:%d:\n%s", before[i].lit, before[i].line, before[i].col, after[i].line, after[i].col, out)
			break
		}
	}

	// A text edit changes the texts, not the Go.
	edited, _, _ := devStaticSrc([]byte(strings.Replace(staticsGo, "Hello", "Hello there", 1)), "f1")
	if string(edited) != string(out) {
		t.Errorf("a text edit changed the Go:\n%s\n---\n%s", out, edited)
	}
	if _, _, ok := devStaticSrc([]byte("package p\n\nimport \"fmt\"\n\nvar _ = fmt.Sprint(\"x\")\n"), "f2"); ok {
		t.Error("a file without ui moved something")
	}
	one, _, ok := devStaticSrc([]byte("package p\n\nimport ui \"github.com/vuka-lang/ui/v2\"\n\nvar _ = ui.HTML(\"<p>a paragraph of text</p>\")\n"), "f3")
	if !ok || !strings.Contains(string(one), `import (vukadevstatic_ "github.com/vuka-lang/vuka/v2/devstatic";ui "github.com/vuka-lang/ui/v2")`) {
		t.Errorf("a single import:\n%s", one)
	}
}

// TestDevStaticsWatch runs vuka run -watch on an app whose page shows a
// shared component, and edits the component: its text, then its props and
// the page passing one. Each edit is served (the texts kept out of the
// component's package are the new ones, and an API change rebuilds the
// page), and the text edit compiles neither the component's package nor
// the page's.
func TestDevStaticsWatch(t *testing.T) {
	if testing.Short() {
		t.Skip("builds the vuka command and an app")
	}
	t.Setenv("GOWORK", "off")
	vuka := buildVuka(t)
	root := localModule(t, webCheckout(t), map[string]string{
		"main.go": e2eMain,
		"pages/index.vuka.html": `<script lang="go">
package pages

import "example.com/app/components"

type Index struct{}
</script>

<main><components.Card Title="Hello" /><span id="label">{components.Label()}</span></main>
`,
		"components/label.vuka": "package components\n\nfunc Label() string { return \"label one\" }\n",
		"components/card.vuka.html": `<script lang="go">
package components

type Card struct {
	Title string
}
</script>

<section class="card">
  <h2>{Title}</h2>
  <p>The card says one.</p>
</section>
`,
	})
	r := startWatch(t, vuka, root, []string{"GOFLAGS=-mod=mod", "VUKA_WATCH_TRACE=1"})
	page := func(want string) {
		t.Helper()
		var body string
		for end := time.Now().Add(3 * time.Minute); time.Now().Before(end); time.Sleep(100 * time.Millisecond) {
			res, err := http.Get(fmt.Sprintf("http://127.0.0.1:%d/", r.port))
			if err != nil {
				continue
			}
			b, _ := io.ReadAll(res.Body)
			res.Body.Close()
			if body = string(b); strings.Contains(body, want) {
				return
			}
		}
		t.Fatalf("no %q in the page %q; output:\n%s", want, body, r.log.String())
	}
	page("The card says one.")
	if !strings.Contains(r.log.String(), "prepare statics") {
		t.Fatalf("the templates' texts weren't kept out of their packages:\n%s", r.log.String())
	}
	card := filepath.Join(root, "components", "card.vuka.html")
	edit := func(path, old, new string) {
		t.Helper()
		src, _ := os.ReadFile(path)
		if !strings.Contains(string(src), old) {
			t.Fatalf("%s has no %q", path, old)
		}
		writeFile(t, path, strings.Replace(string(src), old, new, 1))
	}
	edit(card, "says one", "says two")
	page("The card says two.")
	r.waitLog("● rebuilt in ", 1)

	label := filepath.Join(root, "components", "label.vuka")
	edit(label, "func Label()", "func Extra() int { return 1 }\n\nfunc Label()")
	r.waitLog("transpiled 1 of 3 packages", 1) // components alone: the page names no Extra
	r.waitLog("● rebuilt in ", 2)
	page("label one")
	edit(label, "label one", "label two")
	page("label two")
	edit(label, "func Label() string { return \"label two\" }", "func Label(_ ...int) string { return \"label three\" }")
	page("label three")

	edit(card, "Title string", "Title string\n\tNote  string")
	edit(card, "<p>The card", "<p>{Note}</p>\n  <p>The card")
	edit(filepath.Join(root, "pages", "index.vuka.html"), `Title="Hello"`, `Title="Hello" Note="three"`)
	page("<p>three</p>")
	if strings.Contains(r.log.String(), "devstatic: no fixed HTML") {
		t.Errorf("a text wasn't registered:\n%s", r.log.String())
	}
}
