import "strings"

type Source struct{ table string }

func SourceOf(table string) *Source { return &Source{table} }

type Core struct {
	src    *Source
	filter []string
}

func (c Core) With(f string) Core { return Core{c.src, append(c.filter[:len(c.filter):len(c.filter)], f)} }

// OrderColumns is Order's fields as typed lookups.
