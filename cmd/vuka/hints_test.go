// TestLSPGoplsHint: gopls's errors in the Go of a .vuka file come with the
// build's hints.
func TestLSPGoplsHint(t *testing.T) {
	src := "package main\n\nimport \"fmt\"\n\nfunc main() { fmt.Println(strings.ToUpper(\"x\")) }\n"
	c, dir, _ := startLSPWith(t, map[string]string{"main.vuka": src})
	uri := pathToURI(filepath.Join(dir, "main.vuka"))
	c.notify("textDocument/didOpen", map[string]any{"textDocument": map[string]any{"uri": uri, "languageId": "vuka", "version": 1, "text": src}})
	var got string
	c.waitDiags(uri, func(ds []any) bool {
		got = jsonOf(ds)
		return strings.Contains(got, "undefined: strings")
	})
	col := itoaTest(uint32(strings.Index(src, "strings") - strings.LastIndex(src[:strings.Index(src, "strings")], "\n") - 1))
	for _, want := range []string{`"message":"undefined: strings\nstrings isn't imported\nhelp: import \"strings\""`, `"start":{"character":` + col + `,"line":4}`} {
		if !strings.Contains(got, want) {
			t.Errorf("diagnostics lack %s: %s", want, got)
		}
	}
}

// TestMapGoPositions: an error at an import names the place in the source
// of the Go the go command compiled without line directives.
func TestMapGoPositions(t *testing.T) {
	root := t.TempDir()
	from := []byte("package dep\n\nvar x int = \"s\"\n")
	head := "// Code generated by vuka. DO NOT EDIT.\n\n"
	g := load.Generated{Target: filepath.Join(root, "dep", "dep.go"), Source: filepath.Join(root, "dep", "dep.vuka"), From: from,
		Src: append([]byte(head), from...), Map: transpile.CopyMap(len(head), len(from))}
	msg := "example.com/app/dep doesn't compile: " + g.Target + ":5:13: cannot use \"s\" (untyped string constant) as int value in variable declaration"
	got, spans := mapGoPositions(msg, []load.Generated{g}, root)
	if want := "example.com/app/dep doesn't compile: dep/dep.vuka:3:13: cannot use \"s\" (untyped string constant) as int value in variable declaration"; got != want {
		t.Errorf("got  %s\nwant %s", got, want)
	}
	if len(spans) != 1 || spans[0] != (diag.Span{File: g.Source, Line: 3, Col: 13}) {
		t.Errorf("spans %+v", spans)
	}
}
