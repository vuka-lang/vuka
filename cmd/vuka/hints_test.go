// TestGoHints: what the editor adds to gopls's messages, which have no
// types: the hints read the message and the source.
func TestGoHints(t *testing.T) {
	web := t.TempDir()
	os.WriteFile(filepath.Join(web, "go.mod"), []byte("module example.com/app\n\ngo 1.25.0\n\nrequire github.com/vuka-lang/web/v2 v2.0.0\n"), 0o644)
	os.MkdirAll(filepath.Join(web, "pages", "urls"), 0o755)
	bare := t.TempDir()
	os.WriteFile(filepath.Join(bare, "go.mod"), []byte("module example.com/app\n\ngo 1.25.0\n"), 0o644)
	at := func(src, span string) (int, int) {
		i := strings.Index(src, span)
		return i, i + len(span)
	}
	for _, c := range []struct {
		name, msg, file, src, span string
		root                       string
		want                       hint
	}{
		{"a call in markup without ctx",
			"not enough arguments in call to a.HomePath\n\thave ()\n\twant (context.Context)", "main.vuka.html",
			"<a href={a.HomePath()}>Home</a>\n", "a.HomePath()", bare,
			hint{msg: "not enough arguments in call to a.HomePath", label: "HomePath takes (context.Context)", help: "pass the request's context: a.HomePath(ctx)"}},
		{"a call in markup without ctx, with arguments",
			"not enough arguments in call to urls.User\n\thave (int)\n\twant (context.Context, int)", "main.vuka.html",
			"<a href={urls.User(7)}>Home</a>\n", "urls.User(7)", bare,
			hint{msg: "not enough arguments in call to urls.User", label: "User takes (context.Context, int)", help: "pass the request's context: urls.User(ctx, 7)"}},
		{"a call in markup missing another argument",
			"not enough arguments in call to fmtDate\n\thave (time.Time)\n\twant (time.Time, string)", "main.vuka.html",
			"<p>{fmtDate(t)}</p>\n", "fmtDate(t)", bare,
			hint{msg: "not enough arguments in call to fmtDate", label: "fmtDate takes (time.Time, string)"}},
		{"a call in Go without ctx: no ctx known in scope",
			"not enough arguments in call to get\n\thave ()\n\twant (context.Context)", "main.vuka",
			"x := get()\n", "get()", bare,
			hint{msg: "not enough arguments in call to get", label: "get takes (context.Context)"}},
		{"too many arguments",
			"too many arguments in call to f\n\thave (int, int)\n\twant (int)", "main.vuka",
			"f(1, 2)\n", "2", bare,
			hint{msg: "too many arguments in call to f", label: "f takes (int)"}},
		{"an unused import",
			`"os" imported and not used`, "main.vuka", "import \"os\"\n", `"os"`, bare,
			hint{msg: `"os" imported and not used`, help: "delete the import, or use the package"}},
		{"an attribute of a package not imported",
			"undefined: graphql", "main.vuka", "@graphql.Query\nfunc (q *Q) Users() {}\n", "graphql", web,
			hint{msg: "undefined: graphql", label: "graphql isn't imported", help: `import "github.com/vuka-lang/web/v2/graphql" for @graphql.Query`, span: [2]int{0, 14}}},
		{"an attribute of a package not imported, of a module go.mod doesn't require",
			"undefined: graphql", "main.vuka", "@graphql.Query\nfunc (q *Q) Users() {}\n", "graphql", bare,
			hint{msg: "undefined: graphql", label: "graphql isn't imported", help: "import the package that declares @graphql.Query", span: [2]int{0, 14}}},
		{"a standard package not imported",
			"undefined: strings", "main.vuka", "s := strings.ToUpper(x)\n", "strings", bare,
			hint{msg: "undefined: strings", label: "strings isn't imported", help: `import "strings"`, span: [2]int{5, 12}}},
		{"an undefined name that is no package",
			"undefined: stringz", "main.vuka", "s := stringz.ToUpper(x)\n", "stringz", bare,
			hint{msg: "undefined: stringz"}},
		{"an undefined name that is a package's but isn't used as one",
			"undefined: strings", "main.vuka", "s := strings\n", "strings", bare,
			hint{msg: "undefined: strings"}},
		{"a url that isn't there",
			"urls.Users.Nope undefined (type urls.users has no field or method Nope)", "main.vuka.html", "<a href={urls.Users.Nope.Path()}>x</a>\n", "urls.Users.Nope", web,
			hint{msg: "urls.Users.Nope undefined (type urls.users has no field or method Nope)", note: "the urls package is generated by vuka from the folders under pages/, and no page or folder is Nope there (vuka routes lists them)"}},
		{"a value enum's variant as a method's receiver",
			"PasswordError.Mismatch (constant) is not a type", "main.vuka",
			"func (PasswordError.Mismatch) Error() string { return \"no\" }\n", "PasswordError.Mismatch", bare,
			hint{msg: "PasswordError is a value enum: its variants are values, not types. Write one Error() on PasswordError, or give a variant fields to make it an enum with data."}},
		{"a value enum's variant as a type",
			"Status.Draft (constant) is not a type", "main.vuka",
			"var s Status.Draft\n", "Status.Draft", bare,
			hint{msg: "Status is a value enum: its variants are values, not types. Use Status as the type, or give a variant fields to make it an enum with data."}},
		{"a package's constant as a type",
			"time.Second (constant) is not a type", "main.vuka",
			"var d time.Second\n", "time.Second", bare,
			hint{msg: "time.Second (constant) is not a type"}},
	} {
		t.Run(c.name, func(t *testing.T) {
			from, to := at(c.src, c.span)
			in := hintInput{msg: c.msg, file: c.file, src: []byte(c.src), from: from, to: to, modRoot: c.root, modPath: "example.com/app"}
			in.markup = inMarkup(c.file, in.src, from)
			if got := goHints(in); got != c.want {
				t.Errorf("got  %+v\nwant %+v", got, c.want)
			}
		})
	}
}

// TestBuildHints: the hints of errors the build's own type check finds,
// which knows the types: a signature's parameter names, the ctx in scope,
// the imports of the package's other files. (An attribute's missing import
// stops the transpile first, as E0215.)
func TestBuildHints(t *testing.T) {
	if testing.Short() {
		t.Skip("runs the go command")
	}
	files := map[string]string{
		"main.vuka": `package main

import (
	"context"
	"fmt"
	"os"
)

func get(ctx context.Context, id int) string { return "" }

func main() {
	ctx := context.Background()
	fmt.Println(get(1), strings.ToUpper("x"), web.Version)
}
`,
		"other.go": "package main\n\nimport web \"github.com/vuka-lang/web/v2\"\n\nvar _ = web.New\n",
	}
	root := localModule(t, webCheckout(t), files)
	t.Setenv("GOWORK", "off")
	t.Setenv("GOFLAGS", "-mod=mod")
	t.Chdir(root)
	var stderr bytes.Buffer
	if runGo("build", []string{"-o", filepath.Join(t.TempDir(), "app"), "."}, io.Discard, &stderr) == nil {
		t.Fatal("the build passed")
	}
	golden(t, "hints.golden", stderr.String())
}

