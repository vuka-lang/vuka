// The keep-file is Go's tools.go pattern, written by vuka. A package's real
// imports live in its .vuka files, which plain go tooling can't read, so a
// plain go mod tidy takes a module only they import for unused and drops it
// from go.mod. The keep-file is a .go file go mod tidy can read: it blank-
// imports those packages under a build tag nothing sets, so the go command
// sees the imports and the binary never holds the file. vuka mod tidy and
// vuka build keep it current.
const (
	keepDir  = "vukakeep"
	keepName = "vukakeep.go"
	keepTag  = "vukakeep"
	// keepMark is in the header of every file vuka writes; a file at the
	// keep-file's path without it is the module's own, and left alone.
	keepMark = "generated by vuka"
)

// keepPath is the keep-file's path in the module at root: a directory of
// its own, so its package name conflicts with none of the module's.
func keepPath(root string) string {
	return filepath.Join(root, keepDir, keepName)
}

// isKeepFile reports whether path is the module's keep-file.
func isKeepFile(root, path string) bool {
	return path == keepPath(root)
}

// keepSource is the keep-file for the module at root: a blank import of each
// external package its .vuka and .templ files, or the Go generated from
// them, import, and no hand-written .go file does (go mod tidy sees those
// itself). nil when there are none.
func keepSource(root, modPath string, pkgs []*load.Package, gens []load.Generated) ([]byte, error) {
	seen := importsOf(importStubs(root, pkgs))
	for _, g := range gens {
		for p := range importsOfSrc(g.Target, g.Src) {
			seen[p] = true
		}
	}
	written, err := writtenImports(root)
	if err != nil {
		return nil, err
	}
	var paths []string
	for p := range seen {
		if keepable(p, modPath) && !written[p] {
			paths = append(paths, p)
		}
	}
	if len(paths) == 0 {
		return nil, nil
	}
	sort.Strings(paths)
	var b strings.Builder
	b.WriteString("//go:build " + keepTag + "\n\n")
	b.WriteString("// " + keepMark + " — do not edit. Keeps `go mod tidy` from pruning deps that\n")
	b.WriteString("// are imported only from .vuka files (which go tooling can't read).\n\n")
	b.WriteString("package " + keepDir + "\n\nimport (\n")
	for _, p := range paths {
		b.WriteString("\t_ " + strconv.Quote(p) + "\n")
	}
	b.WriteString(")\n")
	return []byte(b.String()), nil
}

// keepable reports whether the import path is of a package outside the
// standard library and the module: one a requirement provides.
func keepable(path, modPath string) bool {
	if path == "C" || path == modPath || strings.HasPrefix(path, modPath+"/") {
		return false
	}
	first, _, _ := strings.Cut(path, "/")
	return strings.Contains(first, ".")
}

// importsOf is the import paths of each Go source in srcs.
func importsOf(srcs map[string][]byte) map[string]bool {
	out := map[string]bool{}
	for name, src := range srcs {
		for p := range importsOfSrc(name, src) {
			out[p] = true
		}
	}
	return out
}

func importsOfSrc(name string, src []byte) map[string]bool {
	out := map[string]bool{}
	file, _ := parser.ParseFile(token.NewFileSet(), name, src, parser.ImportsOnly)
	if file == nil {
		return out
	}
	for _, imp := range file.Imports {
		if p, err := strconv.Unquote(imp.Path.Value); err == nil {
			out[p] = true
		}
	}
	return out
}

// writtenImports is what the module's .go files on disk import, under any
// build tag: what a plain go mod tidy reads, the keep-file apart. Nested
// modules, and the directories the go command passes over, aren't read.
func writtenImports(root string) (map[string]bool, error) {
	out := map[string]bool{}
	err := filepath.WalkDir(root, func(path string, e fs.DirEntry, err error) error {
		if err != nil {
			return err
		}
		if e.IsDir() {
			if path == root {
				return nil
			}
			name := e.Name()
			if strings.HasPrefix(name, ".") || strings.HasPrefix(name, "_") || name == "testdata" || name == "vendor" {
				return filepath.SkipDir
			}
			if fileExists(filepath.Join(path, "go.mod")) {
				return filepath.SkipDir
			}
			return nil
		}
		if !strings.HasSuffix(e.Name(), ".go") || isKeepFile(root, path) {
			return nil
		}
		src, err := os.ReadFile(path)
		if err != nil {
			return err
		}
		for p := range importsOfSrc(path, src) {
			out[p] = true
		}
		return nil
	})
	return out, err
}

// keepStale reports whether the file at the keep-file's path is other than
// want (nil: none), and errors where it is a file vuka didn't write.
func keepStale(root string, want []byte) (bool, error) {
	have, err := os.ReadFile(keepPath(root))
	if errors.Is(err, fs.ErrNotExist) {
		return want != nil, nil
	}
	if err != nil {
		return false, err
	}
	if !bytes.Contains(have, []byte(keepMark)) {
		return false, fmt.Errorf("%s exists and vuka didn't write it; vuka keeps that path for the file that stops go mod tidy dropping what only .vuka files import", keepPath(root))
	}
	return !bytes.Equal(have, want), nil
}

// writeKeep brings the keep-file to want (nil: none), saying what it did
// to w; it writes only on a change.
func writeKeep(root string, want []byte, w io.Writer) error {
	stale, err := keepStale(root, want)
	if err != nil || !stale {
		return err
	}
	path := keepPath(root)
	rel, _ := filepath.Rel(root, path)
	rel = filepath.ToSlash(rel)
	if want == nil {
		if err := os.Remove(path); err != nil {
			return err
		}
		_ = os.Remove(filepath.Dir(path)) // only if empty
		fmt.Fprintln(w, "removed "+rel)
		return nil
	}
	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		return err
	}
	if err := os.WriteFile(path, want, 0o644); err != nil {
		return err
	}
	fmt.Fprintln(w, "wrote   "+rel)
	return nil
}

// syncKeep is vuka build's refresh of the keep-file: a failure is a
// warning, as the build doesn't need the file.
func syncKeep(root, modPath string, pkgs []*load.Package, gens []load.Generated, stderr io.Writer) {
	want, err := keepSource(root, modPath, pkgs, gens)
	if err == nil {
		err = writeKeep(root, want, io.Discard)
	}
	if err != nil {
		fmt.Fprintln(stderr, "vuka: warning: keep-file:", err)
	}
}
