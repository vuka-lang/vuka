package main

import (
	"bytes"
	"os"
	"os/exec"
	"path/filepath"
	"strings"
	"testing"
)

func TestFixORMFields(t *testing.T) {
	orm := ormDir(t)
	api, _ := os.ReadFile(filepath.Join(orm, "vuka_term.go"))
	if !bytes.Contains(api, []byte("type ModelAnnotation[")) {
		t.Skip("requires the new ORM generator")
	}
	root := localModule(t, webCheckout(t), map[string]string{
		"models.go": `package models
import "github.com/vuka-lang/orm/v2"
type User struct {orm.Model[User];ID int64;Name string}
type Post struct {orm.Model[Post];ID int64;Title string;Author orm.FK[User]}
`,
		"models_gen.go": `// Code generated by ormgen. DO NOT EDIT.
package models
import "github.com/vuka-lang/orm/v2"
type UserPath struct {Name orm.TextField[string]}
var UserFields = UserPath{orm.TextFieldAt[string]("name")}
type PostPath struct {Title orm.TextField[string]}
var PostFields = struct {PostPath; Author UserPath}{PostPath{orm.TextFieldAt[string]("title")},UserPath{orm.TextFieldAt[string]("author__name")}}
`,
		"query.go": `package models
import db "github.com/vuka-lang/orm/v2"
var old []db.Annotation[Post]
// PostFields.Author.Name stays in this comment.
var text = "PostFields.Author.Name"
func title() string {f:=PostFields;return f.Author.Name.Name()}
func (p PostFields) Popular() db.Cond {return p.Title.Eq("popular")}
var constructor = db.Annotation[int]
var method = PostFields.Popular
`,
	})
	withModule(t, root, ormModule, orm)
	t.Setenv("GOWORK", "off")
	t.Setenv("GOFLAGS", "-mod=mod")
	t.Chdir(root)
	var out bytes.Buffer
	if err := fix([]string{"-n", "orm-fields"}, &out); err != nil {
		t.Fatal(err)
	}
	before, _ := os.ReadFile("query.go")
	if !bytes.Contains(before, []byte("f:=PostFields")) {
		t.Fatal("dry run changed the source")
	}
	out.Reset()
	if err := fix([]string{"orm-fields"}, &out); err != nil {
		t.Fatalf("fix: %v\n%s", err, out.String())
	}
	got, _ := os.ReadFile("query.go")
	for _, want := range []string{"[]db.ModelAnnotation[Post]", "f:=PostColumns", "f.Author().Name", "func (p PostFields)", "PostFields.Popular", "db.Annotation[int]", "\"PostFields.Author.Name\"", "// PostFields.Author.Name"} {
		if !strings.Contains(string(got), want) {
			t.Errorf("missing %s:\n%s", want, got)
		}
	}
	cmd := exec.Command("go", "test", "./...")
	cmd.Dir = root
	if b, err := cmd.CombinedOutput(); err != nil {
		t.Fatalf("migrated package: %v\n%s", err, b)
	}
	out.Reset()
	if err := fix([]string{"orm-fields"}, &out); err != nil {
		t.Fatal(err)
	}
	if !strings.Contains(out.String(), "nothing to fix") {
		t.Fatalf("not idempotent: %s", out.String())
	}
}
