// Script islands need no Node: a .ts/.js island exporting island(fn) (or
// mount) bundles as a vanilla one, and a .tsx/.jsx island default-exporting a
// React (or Preact) component is built here by the in-process esbuild with
// React's adapter, react and react-dom (or preact) read from the frontend
// root's node_modules. Framework islands (.vue, .svelte) need Node and the
// project's own toolchain.

// islandModule is vuka:island, what a .ts island imports: island(fn) is
// the island's mount, fn(el, props, ctx) run once, returning { update(next),
// destroy() }; pageIsland(fn) a page-backed one's, fn(el, live).
const islandModuleJS = `
const wrap = (start) => ({ mount(el, props, ctx) {
  const h = start(el, props, ctx) || {};
  return { update: (next) => { if (h.update) h.update(next); }, unmount: () => { if (h.destroy) h.destroy(); } };
} });
export const island = (fn) => wrap(fn);
export const pageIsland = (fn) => wrap((el, props, ctx) => fn(el, ctx.live, props));
`

// islandModuleDTS types vuka:island, written beside vuka-live.d.ts.
const islandModuleDTS = `// Code generated by vuka. DO NOT EDIT.
// A script island: export default island<ChartProps>((el, props, ctx) => …);
// a page backed by one: export default pageIsland<Orders>((el, live) => …).
import type { Live } from "vuka:live";
export interface IslandCtx<P> {
	/** writes a state prop back: the page's ui.State and what reads it */
	set<K extends keyof P>(name: K, v: P[K]): void;
	push(method: string, payload?: unknown): Promise<unknown>;
	emit(name: string, payload?: unknown): Promise<unknown>;
	on(event: string, fn: (payload: any) => void): void;
	ref(name: string): HTMLElement | null;
}
export interface IslandHooks<P> { update?(next: P): void; destroy?(): void; }
export declare function island<P>(fn: (el: HTMLElement, props: P, ctx: IslandCtx<P>) => IslandHooks<P> | void): unknown;
export declare function pageIsland<T>(fn: (el: HTMLElement, live: Live<T>, props: T) => IslandHooks<T> | void): unknown;
`

// islandModulePlugin resolves vuka:island for a vanilla island's bundle.
func islandModulePlugin() api.Plugin {
	return api.Plugin{Name: "vuka-island-module", Setup: func(b api.PluginBuild) {
		b.OnResolve(api.OnResolveOptions{Filter: `^vuka:island$`}, func(api.OnResolveArgs) (api.OnResolveResult, error) {
			return api.OnResolveResult{Path: "island", Namespace: "vuka-island"}, nil
		})
		b.OnLoad(api.OnLoadOptions{Filter: `.*`, Namespace: "vuka-island"}, func(api.OnLoadArgs) (api.OnLoadResult, error) {
			js := islandModuleJS
			return api.OnLoadResult{Contents: &js, Loader: api.LoaderJS}, nil
		})
	}}
}

// reactRuntime is what a frontend root's node_modules has for React islands:
// react and react-dom, else preact (aliased as them), else "".
func reactRuntime(frontendRoot string) string {
	nm := filepath.Join(frontendRoot, "node_modules")
	dir := func(p string) bool { fi, err := os.Stat(filepath.Join(nm, p)); return err == nil && fi.IsDir() }
	switch {
	case dir("react") && dir("react-dom"):
		return "react"
	case dir("preact"):
		return "preact"
	}
	return ""
}

var preactAlias = map[string]string{
	"react":             "preact/compat",
	"react-dom":         "preact/compat",
	"react-dom/client":  "preact/compat/client",
	"react/jsx-runtime": "preact/jsx-runtime",
}

// buildReactIslands builds .tsx/.jsx islands with the in-process esbuild:
// one entry each and React's adapter, split into shared chunks, each chunk
// named <stem>.<hash>.js as /_vuka/i/ serves them.
func buildReactIslands(frontendRoot string, islands []*islandComp, dev bool) ([]*islandBundle, map[string]*manifestIsland, error) {
	rt := reactRuntime(frontendRoot)
	if rt == "" {
		return nil, nil, diag.New("E0603", "react islands need react and react-dom (or preact) in %s", filepath.Join(frontendRoot, "node_modules")).
			WithHelp("run: npm i react react-dom (in %s)", frontendRoot)
	}
	imp, call := findSetup(frontendRoot, "react")
	adapter := adapterSrc("react", imp, call)
	live := liveModules["react"]
	entries := []api.EntryPoint{{InputPath: "vuka-adapter:react", OutputPath: "reactadapter"}}
	keyOf := map[string]string{} // island → entry key
	bySrc := map[string]string{}
	used := map[string]bool{"reactadapter": true}
	for _, ic := range islands {
		if k, ok := bySrc[ic.src]; ok {
			keyOf[ic.name] = k
			continue
		}
		key := jsKeyUnsafe.ReplaceAllString(strings.ToLower(ic.name), "")
		if key == "" {
			key = "island"
		}
		for b, i := key, 2; used[key]; i++ {
			key = fmt.Sprintf("%s%d", b, i)
		}
		used[key], keyOf[ic.name], bySrc[ic.src] = true, key, key
		entries = append(entries, api.EntryPoint{InputPath: ic.src, OutputPath: key})
	}
	opts := api.BuildOptions{
		EntryPointsAdvanced: entries,
		Outdir:              filepath.Join(frontendRoot, ".vuka-island-out"),
		Bundle:              true,
		Format:              api.FormatESModule,
		Splitting:           true,
		Platform:            api.PlatformBrowser,
		Target:              api.ES2020,
		Write:               false,
		Metafile:            true,
		AbsWorkingDir:       frontendRoot,
		NodePaths:           []string{filepath.Join(frontendRoot, "node_modules")},
		JSX:                 api.JSXAutomatic,
		LogLevel:            api.LogLevelSilent,
		Charset:             api.CharsetUTF8,
		EntryNames:          "[name]",
		ChunkNames:          "chunk-[hash]",
		Define:              map[string]string{"process.env.NODE_ENV": `"production"`},
		Plugins: []api.Plugin{{Name: "vuka-react", Setup: func(b api.PluginBuild) {
			b.OnResolve(api.OnResolveOptions{Filter: `^vuka-adapter:react$|^vuka:live$`}, func(a api.OnResolveArgs) (api.OnResolveResult, error) {
				return api.OnResolveResult{Path: a.Path, Namespace: "vuka"}, nil
			})
			b.OnLoad(api.OnLoadOptions{Filter: `.*`, Namespace: "vuka"}, func(a api.OnLoadArgs) (api.OnLoadResult, error) {
				src := live
				if a.Path == "vuka-adapter:react" {
					src = adapter
				}
				return api.OnLoadResult{Contents: &src, Loader: api.LoaderTS, ResolveDir: frontendRoot}, nil
			})
		}}},
	}
	if rt == "preact" {
		opts.Alias = preactAlias
		opts.JSXImportSource = "preact"
	}
	if dev {
		opts.Sourcemap = api.SourceMapInline
		opts.Define["process.env.NODE_ENV"] = `"development"`
	} else {
		opts.MinifyWhitespace, opts.MinifyIdentifiers, opts.MinifySyntax = true, true, true
	}
	res := api.Build(opts)
	if len(res.Errors) > 0 {
		var names []string
		for _, ic := range islands {
			names = append(names, ic.name)
		}
		return nil, nil, islandBuildError(frontendRoot, &islandComp{name: strings.Join(names, ", ")}, res.Errors)
	}
	files, named, err := renameChunks(res, opts.Outdir)
	if err != nil {
		return nil, nil, err
	}
	out := map[string]*manifestIsland{}
	for _, ic := range islands {
		mod := named[keyOf[ic.name]]
		if mod == "" {
			return nil, nil, fmt.Errorf("islands: no chunk emitted for island %s", ic.name)
		}
		out[ic.name] = &manifestIsland{Name: ic.name, Module: mod, Adapter: named["reactadapter"], Framework: "react"}
	}
	return files, out, nil
}

// renameChunks names a split build's outputs as /_vuka/i/ serves them,
// <entry or chunk>.<hash>.js, the imports between them rewritten; named is
// each entry's new name.
func renameChunks(res api.BuildResult, outdir string) ([]*islandBundle, map[string]string, error) {
	var meta struct {
		Outputs map[string]struct {
			Imports []struct {
				Path string `json:"path"`
				Kind string `json:"kind"`
			} `json:"imports"`
			EntryPoint string `json:"entryPoint"`
		} `json:"outputs"`
	}
	if err := json.Unmarshal([]byte(res.Metafile), &meta); err != nil {
		return nil, nil, fmt.Errorf("islands: unreadable metafile: %w", err)
	}
	type chunk struct {
		js      []byte
		imports []string
	}
	chunks := map[string]*chunk{}
	for _, f := range res.OutputFiles {
		if strings.HasSuffix(f.Path, ".js") {
			chunks[filepath.Base(f.Path)] = &chunk{js: f.Contents}
		}
	}
	for out, info := range meta.Outputs {
		c := chunks[filepath.Base(out)]
		if c == nil {
			continue
		}
		for _, im := range info.Imports {
			if im.Kind == "import-statement" || im.Kind == "dynamic-import" {
				c.imports = append(c.imports, filepath.Base(im.Path))
			}
		}
	}
	names := make([]string, 0, len(chunks))
	for n := range chunks {
		names = append(names, n)
	}
	slices.Sort(names)
	final := map[string]string{}
	var order []string
	seen := map[string]bool{}
	var visit func(n string)
	visit = func(n string) {
		if seen[n] || chunks[n] == nil {
			return
		}
		seen[n] = true
		for _, d := range chunks[n].imports {
			visit(d)
		}
		order = append(order, n)
	}
	for _, n := range names {
		visit(n)
	}
	var out []*islandBundle
	named := map[string]string{}
	for _, n := range order {
		c := chunks[n]
		js := string(c.js)
		for _, d := range c.imports {
			if nn := final[d]; nn != "" {
				js = strings.ReplaceAll(js, "./"+d, "./"+nn)
			}
		}
		stem := strings.TrimSuffix(n, ".js")
		if strings.HasPrefix(stem, "chunk-") {
			stem = "chunk"
		}
		sum := sha256.Sum256([]byte(js))
		final[n] = stem + "." + hex.EncodeToString(sum[:4]) + ".js"
		if stem != "chunk" {
			named[stem] = final[n]
		}
		out = append(out, &islandBundle{name: final[n], js: []byte(js)})
	}
	slices.SortFunc(out, func(a, b *islandBundle) int { return strings.Compare(a.name, b.name) })
	return out, named, nil
}
