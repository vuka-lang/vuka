package transpile

import (
	"go/ast"
	"go/format"
	"go/parser"
	"path"
	"slices"
	"strconv"
	"strings"
)

// callAdapters is the package's CallsGoName: vuka.RegisterAdapter for the
// signature of each function a run of call decorators wraps, so vuka.Wrap
// packs its calls without reflection. Generic functions and those of test
// files go through reflection.
func (e *engine) callAdapters() []byte {
	imports := map[string]string{RuntimePath: "vuka"} // path → name
	names := map[string]string{"vuka": RuntimePath}
	seen := map[string]bool{}
	var body strings.Builder
	for _, f := range e.vuka {
		if strings.HasSuffix(f.name, "_test.vuka") || f.dotImps || f.ast == nil {
			continue
		}
		for _, d := range f.decos {
			d, ok := d.(*funcDeco)
			if !ok || !d.wrapped || d.generic || seen[d.fn] {
				continue
			}
			need, ok := e.qualifiers(f, append(slices.Clip(d.ftypes), d.rtypes...))
			if !ok {
				continue
			}
			clash := false
			for name, p := range need {
				if q, ok := names[name]; ok && q != p || p == RuntimePath && name != "vuka" {
					clash = true
				}
			}
			if clash {
				continue
			}
			for name, p := range need {
				names[name], imports[p] = p, name
			}
			seen[d.fn] = true
			body.WriteString(adapter(d))
		}
	}
	if body.Len() == 0 {
		return nil
	}
	var b strings.Builder
	b.WriteString("// Code generated by vuka. DO NOT EDIT.\n\npackage " + e.pkgName() + "\n\n")
	if len(imports) == 1 {
		b.WriteString("import " + strconv.Quote(RuntimePath) + "\n")
		return finishCalls(b.String(), body.String())
	}
	b.WriteString("import (\n")
	paths := make([]string, 0, len(imports))
	for p := range imports {
		paths = append(paths, p)
	}
	slices.Sort(paths)
	slices.SortStableFunc(paths, func(a, b string) int { return cmpBool(isStd(a), isStd(b)) })
	for i, p := range paths {
		if i > 0 && isStd(paths[i-1]) && !isStd(p) {
			b.WriteString("\n")
		}
		if imports[p] == path.Base(p) {
			b.WriteString("\t" + strconv.Quote(p) + "\n")
		} else {
			b.WriteString("\t" + imports[p] + " " + strconv.Quote(p) + "\n")
		}
	}
	b.WriteString(")\n")
	return finishCalls(b.String(), body.String())
}

func finishCalls(head, body string) []byte {
	src, err := format.Source([]byte(head + "\n// The decorated functions' signatures, for vuka.Wrap.\nfunc init() {\n" + body + "}\n"))
	if err != nil {
		return nil
	}
	return src
}

// qualifiers are the packages the type texts name, by the names f imports
// them as; false when one isn't an import of f.
func (e *engine) qualifiers(f *fileState, texts []string) (map[string]string, bool) {
	byName := map[string]string{}
	for _, imp := range f.ast.Imports {
		p, _ := strconv.Unquote(imp.Path.Value)
		name := path.Base(p)
		if imp.Name != nil {
			name = imp.Name.Name
		} else if e.pkg != nil {
			for _, ip := range e.pkg.Imports() {
				if ip.Path() == p {
					name = ip.Name()
				}
			}
		}
		byName[name] = p
	}
	need := map[string]string{}
	ok := true
	for _, t := range texts {
		x, err := parser.ParseExpr(strings.TrimPrefix(t, "..."))
		if err != nil {
			return nil, false
		}
		ast.Inspect(x, func(n ast.Node) bool {
			sel, isSel := n.(*ast.SelectorExpr)
			if !isSel {
				return true
			}
			id, isID := sel.X.(*ast.Ident)
			if !isID {
				return true
			}
			p, found := byName[id.Name]
			if !found {
				ok = false
			}
			need[id.Name] = p
			return false
		})
	}
	return need, ok
}

// adapter is the vuka.RegisterAdapter call for d's signature.
func adapter(d *funcDeco) string {
	var params, args, unpack, rs, outs []string
	for i, t := range d.ftypes {
		a := "a" + itoa(i)
		params = append(params, a+" "+t)
		args = append(args, a)
		in := "vuka.As[" + t + "](a[" + itoa(i) + "])"
		if elem, ok := strings.CutPrefix(t, "..."); ok {
			in = "vuka.As[[]" + elem + "](a[" + itoa(i) + "])..."
		}
		unpack = append(unpack, in)
	}
	for i, t := range d.rtypes {
		rs = append(rs, "r"+itoa(i))
		outs = append(outs, "vuka.As["+t+"](r["+itoa(i)+"])")
	}
	invoke := "next(" + strings.Join(unpack, ", ") + "); return nil"
	if len(rs) > 0 {
		invoke = "return []any{next(" + strings.Join(unpack, ", ") + ")}"
		if len(rs) > 1 {
			invoke = strings.Join(rs, ", ") + " := next(" + strings.Join(unpack, ", ") + ")\n\t\t\treturn []any{" + strings.Join(rs, ", ") + "}"
		}
	}
	call := "call([]any{" + strings.Join(args, ", ") + "}, invoke)"
	ret := "\t\t\t" + call + "\n"
	if len(outs) > 0 {
		ret = "\t\t\tr := " + call + "\n\t\t\treturn " + strings.Join(outs, ", ") + "\n"
	}
	return "\tvuka.RegisterAdapter(func(next " + d.fn + ", call vuka.Caller) " + d.fn + " {\n" +
		"\t\tinvoke := func(a []any) []any {\n\t\t\t" + invoke + "\n\t\t}\n" +
		"\t\treturn func(" + strings.Join(params, ", ") + ")" + d.results + " {\n" + ret + "\t\t}\n\t})\n"
}

// cmpBool orders true first.
func cmpBool(a, b bool) int {
	switch {
	case a == b:
		return 0
	case a:
		return -1
	}
	return 1
}
