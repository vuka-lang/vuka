// The method tables: what Vuka generates for each type whose methods a
// library looks up by name or lists — a live page's events and Update
// overloads, a form's Clean and Choices methods, an island's calls — so
// that the library needn't ask reflect's Method or MethodByName for them.
// One call of either with a name that isn't a constant makes the linker
// keep every exported method of every type the program converts to an
// interface: its dead-method elimination is off for the whole binary.

// Method is a method of a type's method set, as Methods finds it.
type Method struct {
	// Method is as reflect.Type.Method gives it: Type and Func take the
	// receiver first, Index is its place in Methods' answer.
	reflect.Method
	// Decl is the method as declared: Func, or for a method of a pointer
	// type declared on the type it points to, the declared function (where
	// Func is the wrapper the compiler wrote, at <autogenerated>).
	Decl reflect.Value
	// Promoted is the index path of the embedded field a promoted method
	// is the method of, as reflect.Type.FieldByIndex takes it; nil for a
	// method the type declares.
	Promoted []int
}

// RegisterMethods records methods of T, each a method expression as the
// method is declared: T.M, or (*T).M for a method of *T. Generated code
// calls it at init, in the package's vuka_calls_gen.go, for the methods
// the runtime looks up by name.
func RegisterMethods[T any](fns ...any) { registerMethods(reflect.TypeFor[T](), fns) }

func registerMethods(t reflect.Type, fns []any) {
	tab := &methodTable{}
	for _, fn := range fns {
		v := reflect.ValueOf(fn)
		if v.Kind() != reflect.Func || v.Type().NumIn() == 0 {
			panic(fmt.Sprintf("vuka: RegisterMethods[%s] of %T, not a method expression", t, fn))
		}
		_, _, name, _ := parseFuncName(runtime.FuncForPC(v.Pointer()).Name())
		switch v.Type().In(0) {
		case t:
			tab.val = append(tab.val, reflect.Method{Name: name, Type: v.Type(), Func: v})
		case reflect.PointerTo(t):
			tab.ptr = append(tab.ptr, reflect.Method{Name: name, Type: v.Type(), Func: v})
		default:
			panic(fmt.Sprintf("vuka: RegisterMethods[%s] of %T, not a method of %[1]s", t, fn))
		}
	}
	sortMethods(tab.val)
	sortMethods(tab.ptr)
	methodTables.Store(t, tab)
	methodSets.Clear()
}

type methodTable struct{ val, ptr []reflect.Method }

var (
	methodTables sync.Map // reflect.Type (a named type) → *methodTable
	methodSets   sync.Map // reflect.Type → []Method: Methods' answers
)

// Methods are the exported methods of t's method set, sorted by name as
// reflect.Type.Method lists them: those Vuka registered for t's type
// (RegisterMethods), and those its embedded fields promote, as Go
// promotes them. A type Vuka registered no table for has its methods
// found by reflection, except in a program built with the vuka_release
// build tag (vuka build): there it has none.
func Methods(t reflect.Type) []Method {
	if t == nil {
		return nil
	}
	if ms, ok := methodSets.Load(t); ok {
		return ms.([]Method)
	}
	ms, ok := tableMethods(t)
	if !ok {
		if r, found := reflectMethods(t); found {
			ms = r
		}
	}
	for i := range ms {
		ms[i].Index = i
	}
	v, _ := methodSets.LoadOrStore(t, ms)
	return v.([]Method)
}

// MethodByName is t's exported method name, as Methods finds it.
func MethodByName(t reflect.Type, name string) (Method, bool) {
	ms := Methods(t)
	if i, ok := slices.BinarySearchFunc(ms, name, func(m Method, name string) int { return strings.Compare(m.Name, name) }); ok {
		return ms[i], true
	}
	return Method{}, false
}

// Bind is the method bound to recv, a value of the type whose method it
// is: a function value as reflect.Value.Method returns it.
func (m Method) Bind(recv reflect.Value) reflect.Value {
	ft := m.Type
	in := make([]reflect.Type, ft.NumIn()-1)
	for i := range in {
		in[i] = ft.In(i + 1)
	}
	out := make([]reflect.Type, ft.NumOut())
	for i := range out {
		out[i] = ft.Out(i)
	}
	fn := m.Func
	return reflect.MakeFunc(reflect.FuncOf(in, out, ft.IsVariadic()), func(args []reflect.Value) []reflect.Value {
		all := append([]reflect.Value{recv}, args...)
		if ft.IsVariadic() {
			return fn.CallSlice(all)
		}
		return fn.Call(all)
	})
}

// tableMethods is t's method set from the tables: false when t's type has
// none, its embedded fields' promoted methods all it has.
func tableMethods(t reflect.Type) ([]Method, bool) {
	base, ptr := t, false
	if t.Kind() == reflect.Pointer && t.Name() == "" {
		base, ptr = t.Elem(), true
	}
	if base.Name() == "" {
		return nil, false
	}
	var tab *methodTable
	if v, ok := methodTables.Load(base); ok {
		tab = v.(*methodTable)
	}
	var out []Method
	seen := map[string]bool{}
	if tab != nil {
		for _, m := range tab.val {
			if ptr {
				out = append(out, promote(base, true, nil, m)) // the pointer's method set has it too
			} else {
				out = append(out, Method{Method: m, Decl: m.Func})
			}
			seen[m.Name] = true
		}
		if ptr {
			for _, m := range tab.ptr {
				out = append(out, Method{Method: m, Decl: m.Func})
				seen[m.Name] = true
			}
		}
	}
	if base.Kind() == reflect.Struct {
		out = append(out, promotedMethods(base, ptr, seen)...)
	}
	slices.SortFunc(out, func(a, b Method) int { return strings.Compare(a.Name, b.Name) })
	return out, tab != nil
}

// promotedMethods are the methods t's embedded fields promote to t (to *t
// when ptr) from their tables, outside skip: those of the shallowest
// depth that has the name once, a name at that depth twice being
// ambiguous, which shadows it deeper too.
func promotedMethods(t reflect.Type, ptr bool, skip map[string]bool) []Method {
	type embed struct {
		t     reflect.Type // the embedded field's named type
		index []int
		ptr   bool // the field's methods of *t are its method set: the field is a pointer, or addressable
	}
	var out []Method
	level := []embed{{t: t, ptr: ptr}}
	visited := map[reflect.Type]bool{t: true}
	for len(level) > 0 {
		var next []embed
		found := map[string][]Method{}
		for _, e := range level {
			for i := range e.t.NumField() {
				f := e.t.Field(i)
				if !f.Anonymous {
					continue
				}
				ft, fptr := f.Type, e.ptr
				if ft.Kind() == reflect.Pointer {
					ft, fptr = ft.Elem(), true
				}
				if ft.Name() == "" || visited[ft] {
					continue
				}
				index := append(slices.Clip(e.index), i)
				if v, ok := methodTables.Load(ft); ok {
					tab := v.(*methodTable)
					ms := tab.val
					if fptr {
						ms = append(slices.Clip(ms), tab.ptr...)
					}
					for _, m := range ms {
						if !skip[m.Name] {
							found[m.Name] = append(found[m.Name], promote(t, ptr, index, m))
						}
					}
				}
				if ft.Kind() == reflect.Struct {
					next = append(next, embed{t: ft, index: index, ptr: fptr})
				}
			}
		}
		for _, e := range next {
			visited[e.t] = true
		}
		for name, ms := range found {
			skip[name] = true
			if len(ms) == 1 {
				out = append(out, ms[0])
			}
		}
		level = next
	}
	return out
}

// promote is m, a method of the field at index of t, as a method of t (of
// *t when ptr).
func promote(t reflect.Type, ptr bool, index []int, m reflect.Method) Method {
	recv := t
	if ptr {
		recv = reflect.PointerTo(t)
	}
	ft := m.Type
	in := []reflect.Type{recv}
	for i := 1; i < ft.NumIn(); i++ {
		in = append(in, ft.In(i))
	}
	out := make([]reflect.Type, ft.NumOut())
	for i := range out {
		out[i] = ft.Out(i)
	}
	fn, wantPtr := m.Func, ft.In(0).Kind() == reflect.Pointer
	mt := reflect.FuncOf(in, out, ft.IsVariadic())
	call := reflect.MakeFunc(mt, func(args []reflect.Value) []reflect.Value {
		v := args[0]
		if v.Kind() == reflect.Pointer {
			v = v.Elem()
		} else {
			c := reflect.New(v.Type()).Elem()
			c.Set(v)
			v = c
		}
		for _, i := range index {
			if v.Kind() == reflect.Pointer {
				v = v.Elem()
			}
			// as Go promotes it, an unexported field's method too
			f := v.Field(i)
			v = reflect.NewAt(f.Type(), unsafe.Pointer(f.UnsafeAddr())).Elem()
		}
		switch {
		case wantPtr && v.Kind() != reflect.Pointer:
			v = v.Addr()
		case !wantPtr && v.Kind() == reflect.Pointer:
			v = v.Elem()
		}
		args[0] = v
		if ft.IsVariadic() {
			return fn.CallSlice(args)
		}
		return fn.Call(args)
	})
	return Method{Method: reflect.Method{Name: m.Name, Type: mt, Func: call}, Decl: fn, Promoted: index}
}

func sortMethods(ms []reflect.Method) {
	slices.SortFunc(ms, func(a, b reflect.Method) int { return strings.Compare(a.Name, b.Name) })
}
